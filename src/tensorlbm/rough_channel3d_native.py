"""Python driver for the native (C/OpenMP) rough-channel back-end.

The torch implementation in :mod:`tensorlbm.rough_channel3d` is the reference:
readable, unit-tested, and used for every small verification.  A ``ks+`` sweep
over three morphologies and three grids, however, is a few times 10^10
cell-updates — far outside what a Python-level tensor step can do when the
control-plane host is shared.  This module therefore wraps a single C file
(``native/rough_channel3d.c``) that implements *the same* scheme and dumps raw
moment sums, which are then post-processed by
:func:`tensorlbm.rough_channel3d.assemble_channel_record` — the same function
the torch back-end uses, so the two cannot diverge in their physics
definitions, only in floating-point detail.

Design rules
------------
* The C source is compiled on demand with the system ``gcc`` into a cache
  directory (override with ``TENSORLBM_NATIVE_CACHE``), so no binary artefact
  enters the repository and the code stays portable.
* The initial velocity field is generated by
  :func:`tensorlbm.rough_channel3d._initial_velocity` and handed to C verbatim;
  the comparison test in ``tests/test_rough_channel3d.py`` is therefore a
  comparison of the integrators.
* Any failure to compile raises :class:`NativeBackendUnavailable`, so callers
  can fall back to the torch path instead of silently running something else.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path
from typing import Any

import numpy as np

from .rough_channel3d import (
    RoughChannelConfig,
    _initial_velocity,
    assemble_channel_record,
    case_constants,
    geometry_and_mask,
)
from .roughness_elements import RoughnessElementSet

__all__ = ["NativeBackendUnavailable", "native_binary", "run_rough_channel_native", "native_available"]

_SRC = Path(__file__).with_name("native") / "rough_channel3d.c"


class NativeBackendUnavailable(RuntimeError):
    """Raised when the C back-end cannot be built or run on this machine."""


def _cache_dir() -> Path:
    root = os.environ.get("TENSORLBM_NATIVE_CACHE") or os.path.join(tempfile.gettempdir(), "tensorlbm_native")
    path = Path(root)
    path.mkdir(parents=True, exist_ok=True)
    return path


def native_available() -> bool:
    """``True`` when a C compiler is present (does not attempt a build)."""
    return shutil.which("gcc") is not None or shutil.which("cc") is not None


#: Compiler flags of the native back-end.  ``-march=native`` is deliberately
#: *not* the default: on hosts whose GCC auto-vectorises the D3Q19 collision /
#: streaming loops differently from the reference build it produces a solver
#: that diverges after a few hundred steps for parameters that are stable with
#: a plain -O2 build (observed on the 2026-11 amd64 control host: every
#: Re_tau >= 180 case returned NaN with -march=native, all cases ran to
#: convergence with -O2).  Portability beats the last few percent of speed;
#: set ``TENSORLBM_NATIVE_CFLAGS`` to opt in to anything else.
_DEFAULT_CFLAGS: tuple[str, ...] = ("-O3", "-funroll-loops", "-fopenmp")


def _compile_flags() -> list[str]:
    env = os.environ.get("TENSORLBM_NATIVE_CFLAGS")
    if env is not None and env.strip():
        return env.split()
    return list(_DEFAULT_CFLAGS)


def _flags_tag() -> str:
    """Short hash of the flags *and the C source*, so that a cached binary can
    never outlive an edit of ``native/rough_channel3d.c`` (a stale cache hid the
    TRT forcing fix for one full validation run on 2026-11-09)."""
    import hashlib

    h = hashlib.sha1(" ".join(_compile_flags()).encode())
    try:
        h.update(_SRC.read_bytes())
    except OSError:  # pragma: no cover - missing source raises later anyway
        pass
    return h.hexdigest()[:8]


def native_binary(rebuild: bool = False) -> Path:
    """Compile ``native/rough_channel3d.c`` (cached) and return the executable."""
    if not _SRC.is_file():
        raise NativeBackendUnavailable(f"missing C source: {_SRC}")
    compiler = shutil.which("gcc") or shutil.which("cc")
    if compiler is None:
        raise NativeBackendUnavailable("no C compiler (gcc/cc) on PATH")
    out = _cache_dir() / f"rough_channel3d_{_flags_tag()}"
    if out.is_file() and not rebuild:
        return out
    # Compile to a private name and rename: several sweep workers may start at
    # once on the same node and must not race on the shared binary.
    tmp = out.with_name(f"{out.name}.{os.getpid()}.tmp")
    cmd = [compiler, *_compile_flags(), "-o", str(tmp), str(_SRC), "-lm"]
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    if proc.returncode != 0:
        tmp.unlink(missing_ok=True)
        raise NativeBackendUnavailable(f"compile failed: {proc.stderr[-800:]}")
    os.replace(tmp, out)
    return out


def run_rough_channel_native(
    cfg: RoughChannelConfig,
    elements: RoughnessElementSet | None = None,
    *,
    smooth_b_reference: float | None = None,
    smooth_u_plus_bulk: float | None = None,
    binary: Path | None = None,
    rebuild: bool = False,
) -> dict[str, Any]:
    """Run one case with the C back-end; returns the same record as the torch path."""
    solid, kind, ks_nominal, geom = geometry_and_mask(cfg, elements)
    const = case_constants(cfg, solid)
    vel = _initial_velocity(cfg, solid, cfg.u_tau, float(const["nu"]))
    exe = binary or native_binary(rebuild=rebuild)

    with tempfile.TemporaryDirectory(prefix="tblbm_native_") as tmp:
        mask_path = Path(tmp) / "solid.raw"
        init_path = Path(tmp) / "init.f32"
        out_path = Path(tmp) / "out.json"
        mask_path.write_bytes(np.ascontiguousarray(solid.astype(np.uint8)).tobytes())
        init_path.write_bytes(np.ascontiguousarray(vel, dtype=np.float32).tobytes())
        cmd = [
            str(exe),
            str(cfg.nx),
            str(cfg.ny),
            str(cfg.nz),
            repr(float(const["tau"])),
            repr(float(cfg.smagorinsky_cs)),
            repr(float(const["g"])),
            str(int(cfg.steps)),
            str(int(cfg.warmup)),
            str(int(cfg.sample_interval)),
            str(int(cfg.threads)),
            str(mask_path),
            str(out_path),
            str(init_path),
        ]
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=24 * 3600)
        if proc.returncode != 0:
            raise NativeBackendUnavailable(f"native run failed: {proc.stderr[-800:]}")
        raw = json.loads(out_path.read_text())

    for key in ("sum_ux", "sum_ux2", "sum_rho"):
        if raw.get(key) is None:
            raise RuntimeError(
                f"native run diverged: {key} is not finite "
                f"(grid {cfg.nx}x{cfg.ny}x{cfg.nz}, steps {cfg.steps}, tau={const['tau']:.5f})"
            )

    sums = {
        "sum_ux": raw["sum_ux"],
        "sum_ux2": raw["sum_ux2"],
        "sum_rho": raw["sum_rho"],
        "n_samples": raw["n_samples"],
        "max_ux": raw["max_ux"],
    }
    return assemble_channel_record(
        cfg=cfg,
        kind=kind,
        ks_nominal=ks_nominal,
        geom=geom,
        const=const,
        sums=sums,
        prof_sum=np.asarray(raw["prof_sum"], dtype=float),
        backend=f"native-c({np.__name__}-{os.cpu_count()}cpu)",
        wall_seconds=float(raw["wall_seconds"]),
        smooth_b_reference=smooth_b_reference,
        smooth_u_plus_bulk=smooth_u_plus_bulk,
    )