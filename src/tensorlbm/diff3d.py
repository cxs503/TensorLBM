# Forward model
# ---------------------------------------------------------------------------


def feq3d(rho, ux, uy, uz, c, w):
    """D3Q19 equilibrium (second order in u), shape ``(19, nz, ny, nx)``."""
    cu = (c[:, 0].view(-1, 1, 1, 1) * ux.unsqueeze(0)
          + c[:, 1].view(-1, 1, 1, 1) * uy.unsqueeze(0)
          + c[:, 2].view(-1, 1, 1, 1) * uz.unsqueeze(0))
    u2 = ux * ux + uy * uy + uz * uz
    return w.view(-1, 1, 1, 1) * rho.unsqueeze(0) * (
        1.0 + 3.0 * cu + 4.5 * cu * cu - 1.5 * u2.unsqueeze(0))


def macro3d(f, c):
    """Return ``(rho, ux, uy, uz)`` from populations ``f`` ``(19, nz, ny, nx)``."""
    rho = f.sum(dim=0)
    jx = (f * c[:, 0].view(-1, 1, 1, 1)).sum(dim=0)
    jy = (f * c[:, 1].view(-1, 1, 1, 1)).sum(dim=0)
    jz = (f * c[:, 2].view(-1, 1, 1, 1)).sum(dim=0)
    return rho, jx / rho, jy / rho, jz / rho


def collide_bgk3d(f, tau, c, w):
    """SRT collision, differentiable in ``f`` **and** ``tau``."""
    rho, ux, uy, uz = macro3d(f, c)
    feq = feq3d(rho, ux, uy, uz, c, w)
    return f - (f - feq) / tau


def stream3d(f, c):
    """Exact periodic shift ``f_i(x) <- f_i(x - c_i)`` (a permutation)."""
    out = torch.empty_like(f)
    out[0] = f[0]
    for i in range(1, f.shape[0]):
        cx, cy, cz = int(c[i, 0]), int(c[i, 1]), int(c[i, 2])
        out[i] = torch.roll(f[i], shifts=(-cz, -cy, -cx), dims=(0, 1, 2))
    return out


def step3d(f, tau, c, w):
    """One collide-then-stream step ``f^{n+1} = S(C(f^n))``."""
    return stream3d(collide_bgk3d(f, tau, c, w), c)


def abc_initial(n, amp=0.05, eps=0.5, dtype=torch.float64, device=None,
                rho0=1.0):
    """Arnold–Beltrami–Childress initial condition on an ``n^3`` periodic box.

    ``u = A (sin z + cos y, sin x + cos z, cos x + sin y)`` at
    ``x = 2 pi (i + eps) / n`` (cell-centred sampling for ``eps = 0.5``).
    The flow is divergence-free and Beltrami (``curl u = u``), so the nonlinear
    term is a pure gradient and the field is an exact exponentially decaying
    solution of Navier–Stokes — a genuine 3-D (all three components non-zero,
    non-planar) analytic anchor.

    Populations are started at local equilibrium, which leaves acoustic
    transients of relative size ``O(A^2)``; the two-resolution convergence
    study measures their influence.
    """
    c, w = constants(device=device, dtype=dtype)
    t = (torch.arange(n, dtype=dtype, device=device) + eps) * (2.0 * math.pi / n)
    z = t.view(n, 1, 1)
    y = t.view(1, n, 1)
    x = t.view(1, 1, n)
    ux = amp * (torch.sin(z) + torch.cos(y))
    uy = amp * (torch.sin(x) + torch.cos(z))
    uz = amp * (torch.cos(x) + torch.sin(y))
    rho = torch.full((n, n, n), rho0, dtype=dtype, device=device)
    return feq3d(rho, ux, uy, uz, c, w)


def kinetic_energy(f):
    """Objective ``J = 1/2 sum_x |u(x)|^2`` (differentiable)."""
    c, _w = constants(device=f.device, dtype=f.dtype)
    _rho, ux, uy, uz = macro3d(f, c)
    return 0.5 * (ux * ux + uy * uy + uz * uz).sum()


def field_l2_loss(f, target):
    """Quadratic mismatch ``1/2 ||f - f_obs||^2`` (data-assimilation objective)."""
    d = f - target
    return 0.5 * (d * d).sum()


