"""Memory-envelope-bounded reverse-mode differentiation of the 3D D3Q19 BGK LBM.

Gap closed here: ``GAP-DIFFLBM-3D-COST`` — before this module the
differentiable-LBM stack in this repository was **2-D only**
(:mod:`tensorlbm.opt_loop_tau_recovery` differentiates the D3Q19 kernel inside a
single ``z`` plane, i.e. a 2-D physical problem), and no memory / wall-clock
envelope existed for a 3-D inversion.

Forward model (lattice units, periodic box)
-------------------------------------------
D3Q19 BGK, collide-then-stream::

    rho   = sum_i f_i
    j_a   = sum_i c_ia f_i ,   u_a = j_a / rho
    feq_i = w_i rho [1 + 3 c_i.u + 4.5 (c_i.u)^2 - 1.5 u.u]
    f*_i  = f_i - (f_i - feq_i) / tau                (SRT / BGK)
    f'_i  = f*_i (x - c_i)                           (exact shift / periodic)

Weights and velocity set are the standard D3Q19 set of Qian, d'Humières &
Lallemand (1992), *Europhys. Lett.* 17, 479; equilibrium to second order in u
(Succi 2001, *The Lattice Boltzmann Equation*, ch. 5).  Kinematic viscosity
``nu = (tau - 1/2)/3``.

Reverse mode with a fixed state budget (the actual contribution)
----------------------------------------------------------------
Naive reverse mode through ``T`` steps is ``O(T)`` states of memory
(``19 * N^3 * 8`` bytes each; 2.55 GB per state at ``N = 256``).  Two facts give
an ``O(1)``-state budget:

* the VJP of one LBM step needs only the pre-step population, which can be
  regenerated by deterministic recomputation from a stored checkpoint;
* one LBM step is a shallow graph, so its VJP costs ``O(1)`` extra states and
  is obtained exactly in double precision by a single-step autograd call
  ``lambda_n = (d step / d f_n)^T lambda_{n+1}``.

Storing every ``segment``-th state on **disk** (torch files, same out-of-core
idea as the 2-D :mod:`tensorlbm.adjoint.ootc` path) and recomputing the segment
interior gives

    peak RAM ~= 5 states, independent of T,
    recompute factor = 1 + segment/2 forward steps per reverse step.

This is the classical checkpointing / "revolve" trade-off (Griewank 1992, *SIAM
J. Sci. Stat. Comput.* 13, 253; Griewank & Walther 2000, ACM TOMS 26, 136;
Chen et al. 2016 for the deep-learning formulation behind
``torch.utils.checkpoint``).  We deliberately do **not** invert the BGK
collision: the inverse exists (``(1 - 1/tau) f + feq/tau`` is invertible for
tau != 1) but amplifies non-hydrodynamic modes by ``1/|1 - 1/tau|`` per step,
which is numerically unusable for tau < 1 (factor 4 at tau = 0.8).

Verification hooks
------------------
* :func:`full_bptt_gradient` — store-everything reverse mode (``O(T)`` memory);
  the exact reference for the checkpointed path (identical arithmetic).
* :func:`finite_difference_gradient` — central differences with Richardson
  extrapolation; **independent** of the autograd path, used by the acceptance
  gate (relative error <= 1e-6).
* :func:`analytic_decay_gradient` — external anchor.  The Arnold–Beltrami–
  Childress flow ``u = A(sin z + cos y, sin x + cos z, cos x + sin y)`` is
  divergence-free and Beltrami (``curl u = u``), hence an *exact* solution of
  incompressible Navier–Stokes decaying as ``exp(-nu k^2 t)`` (Childress 1970;
  Dombre et al. 1986, *J. Fluid Mech.* 167, 353)::

      J(tau)    = J(0) exp(-2 k^2 T (tau - 1/2)/3)
      dJ/dtau   = -(2/3) k^2 T J(tau)

Usage
-----
>>> from tensorlbm.diff3d import abc_initial, checkpointed_gradient
>>> f0 = abc_initial(16, 0.05)
>>> res = checkpointed_gradient(f0, tau=0.8, steps=64, segment=8)
>>> res.value, res.grad["tau"]
"""

