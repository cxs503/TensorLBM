@dataclass
class GradResult:
    """Container for one gradient evaluation."""

    value: float
    grad: Dict[str, float]
    steps: int
    segment: int
    seconds: float
    dtype: str
    grid: int
    checkpoints: int
    mode: str
    n_forward_steps: int = 0
    bytes_model: float = 0.0
    extra: dict = field(default_factory=dict)


def _leaf(x, dtype, device, requires_grad=True):
    t = torch.tensor(float(x), dtype=dtype, device=device)
    return t.requires_grad_(requires_grad)


def _forward_no_grad(f0, tau, steps, c, w):
    f = f0.detach().clone()
    with torch.no_grad():
        for _ in range(steps):
            f = step3d(f, tau, c, w)
    return f


def checkpointed_gradient(f0, tau, steps, loss_fn: Callable = kinetic_energy,
                          segment: int = 1, dtype=torch.float64, device=None,
                          ckpt_dir: str | None = None,
                          want_grad_f0: bool = True) -> GradResult:
    """Reverse-mode gradient through ``steps`` D3Q19 steps with disk checkpoints.

    Peak RAM is independent of ``steps`` (see :func:`memory_model_bytes`).
    ``segment`` is the checkpoint interval; each segment interior is regenerated
    by deterministic recomputation during the reverse sweep, so memory stays at
    a handful of states while the time overhead is ``1 + segment/2`` forward
    steps per reverse step.
    """
    if segment < 1:
        raise ValueError("segment must be >= 1")
    if steps < 1:
        raise ValueError("steps must be >= 1")
    device = device if device is not None else f0.device
    dtype = dtype if dtype is not None else f0.dtype
    c, w = constants(device=device, dtype=dtype)
    f0 = f0.to(dtype=dtype, device=device)
    n = int(f0.shape[-1])

    tmp = ckpt_dir is None
    ckpt_dir = ckpt_dir or tempfile.mkdtemp(prefix="diff3d_ckpt_")
    os.makedirs(ckpt_dir, exist_ok=True)
    t_start = time.perf_counter()

    # ---- forward sweep: checkpoints to disk, O(1) states in RAM ------------
    f = f0.detach().clone()
    bounds: list[int] = []
    with torch.no_grad():
        for n_step in range(steps):
            if n_step % segment == 0:
                torch.save(f.clone(), os.path.join(ckpt_dir, f"ck_{n_step:07d}.pt"))
                bounds.append(n_step)
            f = step3d(f, tau, c, w)
    f_T = f

    # ---- terminal seed: one shallow graph on the final state ---------------
    f_leaf = f_T.detach().clone().requires_grad_(True)
    value = loss_fn(f_leaf)
    if value.dim() != 0:
        raise ValueError("loss_fn must return a scalar")
    lam = torch.autograd.grad(value, f_leaf)[0].detach()

    grad_tau = torch.zeros((), dtype=dtype, device=device)
    grad_f0 = None
    n_fwd = steps

    # ---- reverse sweep, newest segment first -------------------------------
    for b in reversed(bounds):
        e = min(b + segment, steps)
        ck = torch.load(os.path.join(ckpt_dir, f"ck_{b:07d}.pt"),
                        weights_only=True).to(dtype=dtype, device=device)
        seg_states = [ck]
        with torch.no_grad():
            cur = ck
            for _k in range(e - 1 - b):
                cur = step3d(cur, tau, c, w)
                seg_states.append(cur)
        n_fwd += e - 1 - b
        for k in range(e - 1 - b, -1, -1):
            f_n = seg_states[k].detach().clone().requires_grad_(True)
            tau_leaf = _leaf(tau, dtype, device)
            f_next = step3d(f_n, tau_leaf, c, w)
            g_f, g_tau = torch.autograd.grad(f_next, (f_n, tau_leaf),
                                             grad_outputs=lam)
            grad_tau = grad_tau + g_tau.detach()
            lam = g_f.detach()
        if b == 0 and want_grad_f0:
            grad_f0 = lam.detach().clone()
        seg_states.clear()

    seconds = time.perf_counter() - t_start
    for name in os.listdir(ckpt_dir):
        try:
            os.remove(os.path.join(ckpt_dir, name))
        except OSError:
            pass
    if tmp:
        shutil.rmtree(ckpt_dir, ignore_errors=True)

    res = GradResult(
        value=float(value), grad={"tau": float(grad_tau)}, steps=steps,
        segment=segment, seconds=seconds,
        dtype=str(dtype).replace("torch.", ""), grid=n,
        checkpoints=len(bounds), mode="checkpointed", n_forward_steps=n_fwd,
        bytes_model=float(memory_model_bytes(n, segment, dtype)),
    )
    if grad_f0 is not None:
        res.extra["grad_f0_norm"] = float(grad_f0.norm())
    return res


def full_bptt_gradient(f0, tau, steps, loss_fn: Callable = kinetic_energy,
                       dtype=torch.float64, device=None) -> GradResult:
    """Store-everything reverse mode (``O(steps)`` memory) — internal reference."""
    device = device if device is not None else f0.device
    dtype = dtype if dtype is not None else f0.dtype
    c, w = constants(device=device, dtype=dtype)
    f0 = f0.to(dtype=dtype, device=device)
    tau_leaf = _leaf(tau, dtype, device)
    t_start = time.perf_counter()
    f = f0.clone()
    for _ in range(steps):
        f = step3d(f, tau_leaf, c, w)
    value = loss_fn(f)
    g_tau = torch.autograd.grad(value, tau_leaf)[0]
    return GradResult(
        value=float(value), grad={"tau": float(g_tau)}, steps=steps,
        segment=steps, seconds=time.perf_counter() - t_start,
        dtype=str(dtype).replace("torch.", ""), grid=int(f0.shape[-1]),
        checkpoints=steps, mode="full_bptt", n_forward_steps=steps,
        bytes_model=float(state_bytes(f0.shape[-1], dtype) * (steps + 2)),
    )


def finite_difference_gradient(f0, tau, steps, loss_fn: Callable = kinetic_energy,
                               h: float = 1e-4, richardson: bool = True,
                               dtype=torch.float64, device=None) -> GradResult:
    """Central-difference gradient — independent of the autograd path.

    With ``richardson`` the 4-point extrapolant is returned, cancelling the
    ``O(h^2)`` truncation term::

        g = (8 [J(t+h) - J(t-h)] - [J(t+2h) - J(t-2h)]) / (12 h) + O(h^4)

    This is the correctness reference for the acceptance gate.
    """
    device = device if device is not None else f0.device
    dtype = dtype if dtype is not None else f0.dtype
    c, w = constants(device=device, dtype=dtype)
    f0 = f0.to(dtype=dtype, device=device)

    def J(t):
        f = _forward_no_grad(f0, t, steps, c, w)
        with torch.no_grad():
            return float(loss_fn(f))

    t_start = time.perf_counter()
    if richardson:
        jp1, jm1 = J(tau + h), J(tau - h)
        jp2, jm2 = J(tau + 2 * h), J(tau - 2 * h)
        grad = (8.0 * (jp1 - jm1) - (jp2 - jm2)) / (12.0 * h)
        value = (4.0 * (jp1 + jm1) - (jp2 + jm2)) / 6.0
        nfwd = 4 * steps
    else:
        jp1, jm1 = J(tau + h), J(tau - h)
        grad = (jp1 - jm1) / (2.0 * h)
        value = 0.5 * (jp1 + jm1)
        nfwd = 2 * steps
    return GradResult(
        value=value, grad={"tau": grad}, steps=steps, segment=0,
        seconds=time.perf_counter() - t_start,
        dtype=str(dtype).replace("torch.", ""), grid=int(f0.shape[-1]),
        checkpoints=0,
        mode="richardson_fd" if richardson else "central_fd",
        n_forward_steps=nfwd,
    )


def analytic_decay_gradient(n: int, tau: float, steps: int, amp: float = 0.05,
                            j_value: float | None = None) -> Dict[str, float]:
    """Continuum anchor: ``dJ/dtau`` for the ABC decay with ``J = 1/2 sum |u|^2``.

    ``dJ/dtau = -(2/3) k^2 T J``, ``k = 2 pi / n``.  With ``j_value=None`` the
    continuum decay ``J0 exp(-2 k^2 T (tau - 1/2)/3)`` is used and
    ``J0 = 1.5 n^3 amp^2`` (``<sin^2 + cos^2> = 1`` per component, 3 components).
    """
    k = 2.0 * math.pi / n
    if j_value is None:
        j0 = 1.5 * (n ** 3) * amp * amp
        j_value = j0 * math.exp(-2.0 * k * k * steps * (tau - 0.5) / 3.0)
    return {"j": float(j_value),
            "dJ_dtau": float(-(2.0 / 3.0) * k * k * steps * j_value)}


def recover_tau(f0, f_obs, steps, tau0=0.62, lr=0.02, iters=40, segment=4,
                dtype=torch.float64, device=None, beta1=0.9, beta2=0.999,
                eps=1e-12, lr_floor_frac=0.05):
    """Real inversion loop: recover ``tau`` from a terminal population snapshot.

    ``f_obs`` is the population field at ``t = steps`` produced with the hidden
    relaxation time; the loss is ``1/2 ||f_sim(t; tau) - f_obs||^2`` and every
    gradient comes from :func:`checkpointed_gradient` (the memory-bounded path).
    Adam with cosine-decayed learning rate is used because the objective is
    scale-free in ``tau`` (the terminal state has decayed by orders of
    magnitude, so fixed-step descent overshoots; measured during the audit of
    this module).

    Adam crosses the loss minimum before the cosine schedule has decayed (the
    terminal objective spans four orders of magnitude), so the returned estimate
    is the **best-loss iterate**, not the last one — a standard practice, and
    the full trajectory stays in ``history`` for independent re-checking.

    Returns ``(tau_hat, history)``; ``history`` holds one record per iteration
    with the loss, the gradient, the accepted step and the running best.
    """
    device = device if device is not None else f_obs.device
    dtype = dtype if dtype is not None else f_obs.dtype
    f_obs = f_obs.to(dtype=dtype, device=device)
    f0 = f0.to(dtype=dtype, device=device)
    loss_fn = lambda f, obs=f_obs: field_l2_loss(f, obs)  # noqa: E731
    history = []
    tau_k = float(tau0)
    m = v = 0.0
    best_loss = float("inf")
    best_tau = tau_k
    for it in range(iters):
        res = checkpointed_gradient(f0, tau_k, steps, loss_fn=loss_fn,
                                    segment=segment, dtype=dtype, device=device,
                                    want_grad_f0=False)
        g = res.grad["tau"]
        m = beta1 * m + (1.0 - beta1) * g
        v = beta2 * v + (1.0 - beta2) * g * g
        m_hat = m / (1.0 - beta1 ** (it + 1))
        v_hat = v / (1.0 - beta2 ** (it + 1))
        eta = lr * (lr_floor_frac + (1.0 - lr_floor_frac)
                    * 0.5 * (1.0 + math.cos(math.pi * it / max(iters - 1, 1))))
        step = eta * m_hat / (math.sqrt(v_hat) + eps)
        tau_new = min(max(tau_k - step, 0.5005), 5.0)
        if res.value < best_loss:
            best_loss, best_tau = res.value, tau_k
        history.append({"iter": it, "tau": tau_k, "loss": res.value,
                        "dL_dtau": g, "eta": eta, "d_tau": tau_new - tau_k,
                        "best_tau": best_tau, "best_loss": best_loss})
        if abs(tau_new - tau_k) < 1e-14:
            break
        tau_k = tau_new
    return best_tau, history
