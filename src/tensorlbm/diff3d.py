CS2 = 1.0 / 3.0


def constants(device=None, dtype=torch.float64):
    """D3Q19 velocity set ``c`` (19,3) and weights ``w`` (19,) in ``dtype``.

    The weights are taken from ``d3q19.W_EXACT64`` (exact binary64 rationals,
    ``WEIGHT_PRECISION_SCHEME = rational_binary64_cast_to_runtime_dtype_v1``);
    the public float32 ``d3q19.W`` must **not** be used here because its
    round-off (``sum w = 1 + 1.5e-8``) leaks mass at ``1e-8`` / step, which
    destroys the ``1e-6`` gradient gate.
    """
    return _C.to(dtype=dtype, device=device), _W.to(dtype=dtype, device=device)


