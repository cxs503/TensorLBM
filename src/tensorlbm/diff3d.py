def state_bytes(n, dtype=torch.float64, q=19):
    """Bytes of one ``(q, n, n, n)`` population field."""
    return q * n * n * n * torch.tensor([], dtype=dtype).element_size()


def memory_model_bytes(n, segment=1, dtype=torch.float64, f_obs=False):
    """Analytic peak-RAM model of the checkpointed reverse mode (bytes).

    Counted states: 1 running population (recompute window) + 2 one-step
    autograd temporaries (``feq``, streamed field) + 1 costate ``lambda`` +
    1 terminal state used for the loss / VJP seed + optional observed field.
    Independent of ``steps`` by construction.
    """
    per = state_bytes(n, dtype=dtype)
    return per * (1 + 2 + 1 + 1 + (1 if f_obs else 0))


