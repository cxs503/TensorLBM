"""Compilation and invocation of the native MRT kernels.

The heavy part of the validation face (3D channel LES, long planar runs) is
executed by two C kernels shipped next to this module.  Nothing is pre-built:
each kernel is compiled from source with ``gcc -O3 -fopenmp`` and cached under a
SHA-256 tag, so a stale binary can never masquerade as the current source
(the same discipline as ``tensorlbm.turbulence.les_channel``).

The MRT moment matrix is *generated by Python* and handed to the kernel through
a text file (:func:`matrix_file`), which keeps a single source of truth for the
collision operator across the two languages.
"""

