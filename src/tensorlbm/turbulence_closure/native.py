def run_channel3d(
    *,
    out_prefix: str | Path,
    nx: int,
    ny: int,
    nz: int,
    steps: int,
    warmup: int,
    tau: float,
    force: float,
    cs: float = 0.1,
    wall_mode: int = 0,
    sample_every: int = 20,
    threads: int | None = None,
    build_dir: str | Path | None = None,
) -> dict:
    """Run one D3Q19 MRT channel case."""
    prefix = Path(out_prefix)
    prefix.parent.mkdir(parents=True, exist_ok=True)
    binary = build_kernel("channel3d", build_dir=build_dir)
    mat = matrix_file("D3Q19", build_dir=build_dir)
    cmd = [
        str(binary),
        "--nx", str(nx), "--ny", str(ny), "--nz", str(nz),
        "--steps", str(steps), "--warmup", str(warmup),
        "--sample-every", str(sample_every), "--tau", repr(float(tau)),
        "--cs", repr(float(cs)), "--force", repr(float(force)),
        "--wall", str(int(wall_mode)), "--matrix", str(mat), "--prefix", str(prefix),
    ]
    env = _thread_env(threads, nx * ny * nz)
    started = time.time()
    done = subprocess.run(cmd, capture_output=True, text=True, env=env)
    elapsed = time.time() - started
    if done.returncode != 0:  # pragma: no cover
        raise RuntimeError(f"mrt_channel3d failed: {done.stderr[-2000:]}")
    h = (ny - 2) / 2.0
    payload = {
        "case": {
            "nx": nx, "ny": ny, "nz": nz, "steps": steps, "warmup": warmup,
            "tau": tau, "nu": (tau - 0.5) / 3.0, "cs": cs, "force": force,
            "h": h, "u_tau_target": float(np.sqrt(force * h)), "wall_mode": wall_mode,
        },
        "artefacts": {
            "profile": str(prefix) + "_profile.txt",
            "diag": str(prefix) + "_diag.txt",
        },
        "provenance": _provenance(binary, elapsed, nx * ny * nz * steps),
        "stderr_tail": done.stderr.strip().splitlines()[-3:],
    }
    Path(str(prefix) + "_run.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return payload


def read_profile(prefix: str | Path) -> dict[str, np.ndarray]:
    data = np.loadtxt(str(Path(str(prefix) + "_profile.txt")))
    return {
        "y": data[:, 0],
        "u_mean": data[:, 1],
        "u_rms": data[:, 2],
        "uy_rms": data[:, 3],
        "count": data[:, 4],
    }


def read_diag(prefix: str | Path) -> dict[str, np.ndarray]:
    data = np.loadtxt(str(Path(str(prefix) + "_diag.txt")))
    data = np.atleast_2d(data)
    return {
        "step": data[:, 0],
        "ke": data[:, 1],
        "umax": data[:, 2],
        "utau_wall": data[:, 3],
        "mass": data[:, 4],
    }