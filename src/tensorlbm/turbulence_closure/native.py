# planar D2Q9 cases (backward facing step / circular cylinder)
# ---------------------------------------------------------------------------

def run_d2q9(
    *,
    out_prefix: str | Path,
    nx: int,
    ny: int,
    solid: np.ndarray,
    body: np.ndarray | None,
    steps: int,
    warmup: int,
    u_in: float,
    tau: float,
    cs: float = 0.0,
    body_force: float = 0.0,
    periodic_x: bool = False,
    parabolic: bool = False,
    inlet_y0: float | None = None,
    inlet_y1: float | None = None,
    sample_every: int = 20,
    force_every: int = 1,
    threads: int | None = None,
    build_dir: str | Path | None = None,
) -> dict:
    """Run one planar case; returns a dict with meta + parsed diagnostics."""
    prefix = Path(out_prefix)
    prefix.parent.mkdir(parents=True, exist_ok=True)
    solid = np.asarray(solid, dtype=np.int32)
    if solid.shape != (ny, nx):
        raise ValueError("solid mask shape must be (ny, nx)")
    if solid[0].any() is False or solid[-1].any() is False:
        raise ValueError("the solid mask must contain walls on y=0 and y=ny-1")
    mask_path = Path(str(prefix) + ".mask.txt")
    np.savetxt(mask_path, solid.reshape(-1), fmt="%d")
    body_path = None
    if body is not None:
        body_path = Path(str(prefix) + ".body.txt")
        np.savetxt(body_path, np.asarray(body, dtype=np.int32).reshape(-1), fmt="%d")

    binary = build_kernel("d2q9", build_dir=build_dir)
    mat = matrix_file("D2Q9", build_dir=build_dir)
    cmd = [
        str(binary),
        "--nx", str(nx), "--ny", str(ny),
        "--steps", str(steps), "--warmup", str(warmup),
        "--sample-every", str(sample_every), "--force-every", str(force_every),
        "--u-in", repr(float(u_in)), "--tau", repr(float(tau)), "--cs", repr(float(cs)),
        "--matrix", str(mat), "--mask", str(mask_path), "--prefix", str(prefix),
    ]
    if body_path is not None:
        cmd += ["--body", str(body_path)]
    if body_force:
        cmd += ["--body-force", repr(float(body_force))]
    if periodic_x:
        cmd += ["--periodic-x"]
    if parabolic:
        cmd += ["--parabolic"]
    if inlet_y0 is not None:
        cmd += ["--inlet-y0", repr(float(inlet_y0))]
    if inlet_y1 is not None:
        cmd += ["--inlet-y1", repr(float(inlet_y1))]
    env = _thread_env(threads, nx * ny)
    started = time.time()
    done = subprocess.run(cmd, capture_output=True, text=True, env=env)
    elapsed = time.time() - started
    if done.returncode != 0:  # pragma: no cover
        raise RuntimeError(f"mrt_d2q9 failed: {done.stderr[-2000:]}")
    payload = {
        "case": {
            "nx": nx, "ny": ny, "steps": steps, "warmup": warmup, "u_in": u_in,
            "tau": tau, "nu": (tau - 0.5) / 3.0, "cs": cs, "body_force": body_force,
            "periodic_x": periodic_x, "parabolic": parabolic,
        },
        "artefacts": {
            "mean": str(prefix) + "_mean.txt",
            "force": str(prefix) + "_force.txt",
            "diag": str(prefix) + "_diag.txt",
        },
        "provenance": _provenance(binary, elapsed, nx * ny * steps),
        "stderr_tail": done.stderr.strip().splitlines()[-3:],
    }
    Path(str(prefix) + "_run.json").write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return payload


def read_force_series(prefix: str | Path) -> dict[str, np.ndarray]:
    path = Path(str(prefix) + "_force.txt")
    data = np.loadtxt(path)
    data = np.atleast_2d(data)
    return {"step": data[:, 0], "fx": data[:, 1], "fy": data[:, 2]}


def read_mean_field(prefix: str | Path, nx: int, ny: int) -> dict[str, np.ndarray]:
    path = Path(str(prefix) + "_mean.txt")
    data = np.genfromtxt(path, names=["x", "y", "rho", "ux", "uy"])
    out = {}
    for name in ("rho", "ux", "uy"):
        out[name] = data[name].reshape(ny, nx)
    out["solid"] = np.isnan(out["ux"])
    return out


def read_meta(prefix: str | Path) -> dict[str, str]:
    path = Path(str(prefix) + "_meta.txt")
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line:
            key, val = line.split("=", 1)
            out[key] = val
    return out


