# Physics anchor: prescribed co-rotating vortex pair (Lighthill 1952)
# ---------------------------------------------------------------------------

def co_rotating_vortex_pair(
    xx: np.ndarray,
    yy: np.ndarray,
    gamma: float,
    half_separation: float,
    core_radius: float,
    t: float,
    rho0: float = 1.0,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    r"""Prescribed co-rotating vortex pair field (analytic, incompressible).

    Two Lamb-type vortices of circulation ``Γ`` separated by ``2d`` rotate
    rigidly with angular velocity ``Ω = Γ/(4πd²)`` (each vortex is advected by
    the other's induced velocity ``Γ/(4πd)``).  The field is *prescribed* —
    i.e. the flow is taken as frozen in the co-rotating frame and rotated
    rigidly — which is the standard low-Mach aeroacoustic source model: at
    ``M ≪ 1`` the incompressible field is the correct leading-order Lighthill
    source, while the acoustic wavelength ``λ = πd/M`` is far too large to be
    resolved by a compressible flow solver.

    The thermodynamic state follows Bernoulli + isentropic closure,
    ``p' = -½ρ₀|u|²``, ``ρ = ρ₀ + p'/c₀²``, so that the compressible part of
    the Lighthill tensor ``δ_ij(p - c₀²ρ)`` cancels identically to leading
    order (isentropy) — a property the tests assert explicitly.

    Args:
        xx, yy: Mesh coordinates (any common shape).
        gamma: Circulation of each vortex (same sign → co-rotating).
        half_separation: ``d`` in the formula above.
        core_radius: Gaussian core radius ``r_c``.
        t: Physical time.
        rho0: Undisturbed density.

    Returns:
        ``(rho, ux, uy)``.
    """
    omega_rot = gamma / (4.0 * math.pi * half_separation ** 2)
    ang = omega_rot * t
    ca, sa = math.cos(ang), math.sin(ang)
    xr = ca * xx + sa * yy
    yr = -sa * xx + ca * yy

    ux = np.zeros_like(xx, dtype=float)
    uy = np.zeros_like(xx, dtype=float)
    for sgn in (+1.0, -1.0):
        ddx = xr - sgn * half_separation
        ddy = yr.copy()
        r2 = ddx ** 2 + ddy ** 2 + 1e-30
        f = gamma / (2.0 * math.pi) * (1.0 - np.exp(-r2 / core_radius ** 2)) / r2
        ux += -f * ddy
        uy += f * ddx

    ux_l = ca * ux - sa * uy
    uy_l = sa * ux + ca * uy
    return ux_l, uy_l


def rotating_quadrupole_analysis(
    p_hat: np.ndarray,
    angles: np.ndarray,
    omega: float,
    n_modes: int = 3,
) -> dict:
    r"""Decompose a 2-D rotating-quadrupole far field ``p̂(θ)``.

    A rigidly rotating quadrupole radiates a field whose *complex* amplitude is

        p̂(θ) = p_m e^{i m θ},   m = ±2

    i.e. the amplitude ``|p̂|`` is **angularly isotropic** while the phase winds
    with integer winding number ``m``.  The familiar four-lobe ``|cos 2θ|``
    directivity is the *phase-locked instantaneous* pattern

        p(θ, t₀) = Re[p̂(θ) e^{iωt₀}],

    which rotates at ``Ω = ω/2``.  Reporting a time-averaged RMS directivity
    for such a source therefore yields (spuriously) an isotropic pattern — a
    trap documented in the module notes.

    Args:
        p_hat: Complex pressure amplitude ``(N_obs,)``.
        angles: Observer azimuths ``(N_obs,)`` in radians.
        omega: Angular frequency of the analysed component.
        n_modes: Number of azimuthal modes to report (``m = 0..n_modes``).

    Returns:
        Dictionary with ``winding`` (phase slope), ``isotropy``
        (``(max-min)/mean`` of ``|p̂|``), ``modes`` (``{m: complex amplitude}``),
        ``pattern`` (phase-locked instantaneous pattern) and
        ``pattern_corr_cos2`` / ``pattern_corr_sin2`` correlations against the
        ideal four-lobe shapes.
    """
    p_hat = np.asarray(p_hat)
    angles = np.asarray(angles)
    n = angles.size

    modes = {}
    for m in range(-n_modes, n_modes + 1):
        modes[m] = complex(np.sum(p_hat * np.exp(-1j * m * angles)) / n)

    abs_p = np.abs(p_hat)
    isotropy = float((abs_p.max() - abs_p.min()) / (abs_p.mean() + 1e-300))
    winding = float(np.polyfit(angles, np.unwrap(np.angle(p_hat)), 1)[0])

    dom_m = max((m for m in modes if m != 0), key=lambda m: abs(modes[m]))
    t0 = -np.angle(p_hat[0]) / omega
    pattern = np.real(p_hat * np.exp(1j * omega * t0))
    pat_abs = np.abs(pattern)
    corr_cos = float(np.corrcoef(pat_abs, np.abs(np.cos(2 * angles)))[0, 1])
    corr_sin = float(np.corrcoef(pat_abs, np.abs(np.sin(2 * angles)))[0, 1])

    return {
        "winding": winding,
        "isotropy": isotropy,
        "modes": modes,
        "dominant_mode": int(dom_m),
        "amplitude": abs(modes[dom_m]),
        "pattern": pattern,
        "pattern_corr_cos2": corr_cos,
        "pattern_corr_sin2": corr_sin,
        "t_ref": t0,
    }
