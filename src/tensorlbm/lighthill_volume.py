def analytical_gaussian_quadrupole_farfield(
    observer_positions: np.ndarray,
    omega: float,
    c0: float,
    amplitude: float = 1.0,
    sigma: float = 2.0,
    source_center: Tuple[float, float] = (0.0, 0.0),
    quadrupole_type: str = "xx-yy",
) -> np.ndarray:
    """Analytical far-field for a Gaussian quadrupole (point-quadrupole limit).

    For r >> σ, the Gaussian source integrates to a point quadrupole:
        Q_ij = A_ij · π σ²
    and the far-field is:
        p̂(x) = Q_ij ∂²G/∂x_i∂x_j (x - x₀)

    Args:
        observer_positions: ``(N, 2)``.
        omega: Angular frequency.
        c0: Speed of sound.
        amplitude: Source amplitude.
        sigma: Gaussian width.
        source_center: Source center.
        quadrupole_type: "xx-yy" for cos(2θ), "xy" for sin(2θ).

    Returns:
        Complex pressure ``(N,)``.
    """
    if quadrupole_type == "xx-yy":
        A_ij = np.array([[amplitude, 0], [0, -amplitude]], dtype=np.complex128)
    elif quadrupole_type == "xy":
        A_ij = np.array([[0, amplitude], [amplitude, 0]], dtype=np.complex128)
    else:
        raise ValueError(f"Unknown quadrupole_type: {quadrupole_type}")

    Q_ij = A_ij * np.pi * sigma**2

    d2G = _green_2d_d2_point_source(observer_positions, np.array(source_center), omega, c0)

    # Contract: p = Q_ij d2G_ij
    p_hat = np.einsum('ij,oij->o', Q_ij, d2G)
    return p_hat


def compact_quadrupole_power(
    Q_ij: np.ndarray,
    omega: float,
    c0: float,
    rho0: float = 1.0,
    ndim: int = 2,
) -> float:
    r"""Acoustic power radiated by a compact quadrupole (trace-free part).

    Derived from the compact far field ``p̂ = -k² Q_ij x̂_i x̂_j (i/4)H₀⁽¹⁾(kr)``
    (2-D) / ``p̂ = -k² Q_ij x̂_i x̂_j e^{ikr}/(4πr)`` (3-D) by integrating the
    time-averaged intensity ``|p̂|²/(2ρ₀c₀)`` over a circle/sphere:

    .. math::

        2\text{-D (per unit length)}:\quad \frac{P}{L}
            = \frac{\omega^3 Q_{ij}Q_{ij}}{32\,\rho_0 c_0^4}

        3\text{-D}:\quad P = \frac{\omega^4 Q_{ij}Q_{ij}}
            {60\pi\,\rho_0 c_0^5}

    with ``Q_ij = ∫ T_ij dA`` (2-D, per unit length) or ``∫ T_ij dV`` (3-D)
    in the *stress-tensor* normalisation used throughout this module (i.e. the
    same ``Q_ij`` that enters :func:`analytical_gaussian_quadrupole_farfield`).

    .. note::
       Both formulas were corrected in mission P170W2B-N03: the inherited
       2-D branch was dimensionally inconsistent (``ρ₀ω⁵Q²/(64πc₀⁴)``) and the
       3-D branch carried an extra ``ω²/ρ₀²``.  Both are now verified against
       the numerical far-field intensity integral
       (``tests/test_lighthill_volume_maturation.py::test_compact_power_closed_form``)
       to < 2 %.

    Args:
        Q_ij: Quadrupole moment matrix (``d × d``, symmetric).
        omega: Angular frequency.
        c0: Speed of sound.
        rho0: Undisturbed density.
        ndim: 2 (per unit length) or 3.

    Returns:
        Acoustic power (W) or power per unit length (W/m).
    """
    Q_ij = np.asarray(Q_ij)
    d = Q_ij.shape[0]
    trace = np.trace(Q_ij)
    Q_tf = Q_ij - (trace / d) * np.eye(d)
    contraction = float(np.sum(Q_tf * np.conj(Q_tf)).real)

    if ndim == 3:
        return float(omega ** 4 * contraction / (60.0 * math.pi * rho0 * c0 ** 5))
    return float(omega ** 3 * contraction / (32.0 * rho0 * c0 ** 4))


# ---------------------------------------------------------------------------
# Kirchhoff surface integral (for cross-validation)
# ---------------------------------------------------------------------------

def kirchhoff_surface_2d(
    p_surface: np.ndarray,
    dp_dn_surface: np.ndarray,
    surface_positions: np.ndarray,
    surface_normals: np.ndarray,
    surface_weights: np.ndarray,
    observer_positions: np.ndarray,
    omega: float,
    c0: float,
) -> np.ndarray:
    """2-D frequency-domain Kirchhoff surface integral (vectorized).

    p̂(x) = ∫_S [p̂ ∂G/∂n - G ∂p̂/∂n] dS
    """
    k = omega / c0
    # r_vec[o, s] = obs[o] - src[s]
    r_vec = observer_positions[:, None, :] - surface_positions[None, :, :]
    r = np.linalg.norm(r_vec, axis=-1)
    r_safe = np.maximum(r, 1e-15)
    kr = k * r_safe

    G = 0.25j * hankel1(0, kr)
    G_prime = -0.25j * k * hankel1(1, kr)

    r_hat = r_vec / r_safe[..., None]
    dG_dn = G_prime * np.sum(r_hat * surface_normals[None, :, :], axis=-1)

    integrand = p_surface[None, :] * dG_dn - G * dp_dn_surface[None, :]
    return np.sum(integrand * surface_weights[None, :], axis=1)


