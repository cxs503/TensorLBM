def gaussian_quadrupole_farfield_exact(
    observer_positions: np.ndarray,
    omega: float,
    c0: float,
    amplitude: float = 1.0,
    sigma: float = 1.0,
    source_center: Tuple[float, float] = (0.0, 0.0),
    quadrupole_type: str = "xx-yy",
) -> np.ndarray:
    r"""Exact leading far-field (stationary-phase) closed form, 2-D.

    For a Gaussian quadrupole source ``T_ij(y) = A_ij exp(-|y-y0|²/σ²)`` the
    exact far-field of

        p̂(x) = ∫ T_ij(y) ∂_i∂_j G(|x-y|) dA(y),      G = (i/4) H₀⁽¹⁾(kr)

    is obtained by (i) the stationary-phase substitution
    ``∂_i∂_j G → -k² x̂_i x̂_j G`` (error ``O(1/(kr))``), and (ii) the exact 2-D
    Fourier transform of the Gaussian source:

        ∫ exp(-|y|²/σ²) e^{-i k x̂·y} dA = πσ² exp(-k²σ²/4)

    hence

        p̂(x) = -k² (i/4) H₀⁽¹⁾(kr) · x̂_i x̂_j A_ij · πσ² · exp(-k²σ²/4)

    Unlike the point-quadrupole limit (``analytical_gaussian_quadrupole_farfield``)
    the ``exp(-k²σ²/4)`` factor is retained, so the formula stays valid for
    **non-compact** sources (σ/λ up to ≈0.2) and lets the integration operator
    itself be verified below the 2 % level without a compactness bias.

    Args:
        observer_positions: ``(N, 2)`` observer coordinates.
        omega: Angular frequency.
        c0: Speed of sound.
        amplitude: Source amplitude (units of T).
        sigma: Gaussian width.
        source_center: Source centroid.
        quadrupole_type: ``"xx-yy"`` (∝ cos 2θ) or ``"xy"`` (∝ sin 2θ).

    Returns:
        Complex pressure amplitude ``(N,)`` with convention
        ``p(t) = Re[p̂ e^{iωt}]``.
    """
    obs = np.atleast_2d(np.asarray(observer_positions, dtype=float))
    k = omega / c0
    r_vec = obs - np.asarray(source_center, dtype=float)[None, :]
    r = np.linalg.norm(r_vec, axis=-1)
    r_safe = np.maximum(r, 1e-300)
    xh = r_vec / r_safe[:, None]

    A = _quadrupole_amplitude(amplitude, quadrupole_type)
    xhAx = np.einsum('ni,ij,nj->n', xh, A, xh)

    finite_size = math.pi * sigma ** 2 * math.exp(-(k * sigma) ** 2 / 4.0)
    return (-k ** 2) * 0.25j * hankel1(0, k * r_safe) * finite_size * xhAx


def _quadrupole_amplitude(amplitude: float, quadrupole_type: str) -> np.ndarray:
    """Return the 2-D quadrupole amplitude matrix ``A_ij``."""
    if quadrupole_type == "xx-yy":
        return np.array([[amplitude, 0.0], [0.0, -amplitude]], dtype=np.complex128)
    if quadrupole_type == "xy":
        return np.array([[0.0, amplitude], [amplitude, 0.0]], dtype=np.complex128)
    raise ValueError(f"Unknown quadrupole_type: {quadrupole_type}")


def gaussian_quadrupole_farfield_3d(
    observer_positions: np.ndarray,
    omega: float,
    c0: float,
    amplitude: float = 1.0,
    sigma: float = 1.0,
    source_center: Tuple[float, float, float] = (0.0, 0.0, 0.0),
    quadrupole_type: str = "xx-yy",
) -> np.ndarray:
    """Exact leading far-field closed form for a 3-D Gaussian quadrupole.

    ``p̂(x) = -k² (e^{ikr}/4πr) · x̂_i x̂_j A_ij · π^{3/2}σ³ e^{-k²σ²/4}``
    """
    obs = np.atleast_2d(np.asarray(observer_positions, dtype=float))
    k = omega / c0
    r_vec = obs - np.asarray(source_center, dtype=float)[None, :]
    r = np.linalg.norm(r_vec, axis=-1)
    r_safe = np.maximum(r, 1e-300)
    xh = r_vec / r_safe[:, None]

    a = amplitude
    if quadrupole_type == "xx-yy":
        A = np.diag([a, -a, 0.0]).astype(np.complex128)
    elif quadrupole_type == "xy":
        A = np.array([[0, a, 0], [a, 0, 0], [0, 0, 0]], dtype=np.complex128)
    else:
        raise ValueError(f"Unknown quadrupole_type: {quadrupole_type}")
    xhAx = np.einsum('ni,ij,nj->n', xh, A, xh)

    finite_size = math.pi ** 1.5 * sigma ** 3 * math.exp(-(k * sigma) ** 2 / 4.0)
    green = np.exp(1j * k * r_safe) / (4.0 * math.pi * r_safe)
    return (-k ** 2) * green * finite_size * xhAx


def volume_quadrupole_time_domain(
    T_field: np.ndarray,
    dx: float,
    observers: np.ndarray,
    c0: float,
    dt: float,
    grid_origin: Tuple[float, float, float] = (0.0, 0.0, 0.0),
    source_chunk: int = 4096,
    include_near_field: bool = True,
) -> Tuple[np.ndarray, np.ndarray]:
    r"""Retarded-time (delayed-time) 3-D Ffowcs Williams-Hawkings volume term.

    Implements the delayed-time form of the Lighthill/FW-H quadrupole integral
    for a medium at rest (Brentner & Farassat 2003, formulation 1A):

    .. math::

        p'_Q(\mathbf{x},t) = \frac{1}{4\pi}\Big[
            \frac{1}{c_0^2}\frac{\partial^2}{\partial t^2}
              \int_V \frac{[T_{rr}]}{r}\,dV
            - \frac{1}{c_0}\frac{\partial}{\partial t}
              \int_V \frac{[3T_{rr}-T_{ii}]}{r^2}\,dV
            + \int_V \frac{[3T_{rr}-T_{ii}]}{r^3}\,dV \Big]

    with ``T_rr = T_ij r̂_i r̂_j`` (``r̂`` the source→observer unit vector) and
    ``[·]`` denoting evaluation at the retarded time ``t - r/c₀``.  The first
    bracket is the classical ``∂²/∂t²`` far-field quadrupole term; the second
    and third are its ``O(1/(kr))`` and ``O(1/(kr)²)`` near-field corrections,
    which are obtained analytically from the exact 3-D kernel
    ``∂_i∂_j G = [-k² - 3ik/r + 3/r²]G r̂_i r̂_j + [ik/r - 1/r²]G δ_ij``
    (``include_near_field=False`` recovers the widely used far-field-only
    form, useful for error-budget studies).

    The retarded source time is resolved by linear interpolation of the stored
    history, so the reduced-frequency error is ``O((ωΔt)²)``; the second time
    derivative is a centred second difference.  The history must therefore be
    long enough to contain the retarded window: ``n_t·dt > r_max/c₀`` plus the
    interval to be analysed.

    Args:
        T_field: Lighthill tensor history ``(n_t, nz, ny, nx, 3, 3)``.
        dx: Isotropic grid spacing.
        observers: ``(N_obs, 3)`` observer positions.
        c0: Speed of sound.
        dt: Time step of the source history.
        grid_origin: Physical coordinate of voxel ``(0, 0, 0)`` — use
            ``(-(n//2)*dx, ...)`` to centre the grid on the origin.
        source_chunk: Sources processed per memory chunk.
        include_near_field: Include the ``1/r²`` and ``1/r³`` corrections.

    Returns:
        ``(p_prime, t)`` with ``p_prime`` of shape ``(N_obs, n_t - 2)``.
    """
    T_field = np.asarray(T_field)
    if T_field.ndim != 6 or T_field.shape[-1] != 3:
        raise ValueError("T_field must have shape (n_t, nz, ny, nx, 3, 3)")
    n_t, nz, ny, nx = T_field.shape[:4]

    gx = grid_origin[0] + np.arange(nx) * dx
    gy = grid_origin[1] + np.arange(ny) * dx
    gz = grid_origin[2] + np.arange(nz) * dx
    zz, yy, xx = np.meshgrid(gz, gy, gx, indexing='ij')
    src = np.stack([xx.ravel(), yy.ravel(), zz.ravel()], axis=-1)
    dV = dx ** 3

    observers = np.atleast_2d(np.asarray(observers, dtype=float))
    n_obs = observers.shape[0]
    t_obs = np.arange(n_t) * dt

    acc1 = np.zeros((n_obs, n_t))
    acc2 = np.zeros((n_obs, n_t))
    acc3 = np.zeros((n_obs, n_t))

    T_flat = T_field.reshape(n_t, -1, 3, 3)

    for o in range(n_obs):
        a1 = np.zeros(n_t)
        a2 = np.zeros(n_t)
        a3 = np.zeros(n_t)
        for s0 in range(0, src.shape[0], source_chunk):
            s1 = min(s0 + source_chunk, src.shape[0])
            r_vec = observers[o][None, :] - src[s0:s1]           # (m, 3)
            r = np.linalg.norm(r_vec, axis=-1)
            r_safe = np.maximum(r, 1e-300)
            r_hat = r_vec / r_safe[:, None]
            flip = r_hat[..., :, None] * r_hat[..., None, :]     # (m, 3, 3)
            Tblk = T_flat[:, s0:s1]
            T_rr = np.einsum('mij,tmij->tm', flip, Tblk)
            T_ii = np.einsum('tmii->tm', Tblk)
            comb = 3.0 * T_rr - T_ii

            delay = r_safe / c0
            pos = (t_obs[:, None] - delay[None, :]) / dt           # (n_t, m)
            idx = np.floor(pos).astype(np.int64)
            frac = pos - idx
            inside = (idx >= 0) & (idx <= n_t - 2)
            idx_c = np.clip(idx, 0, n_t - 2)
            cols = np.arange(r_safe.size)[None, :]
            for k, (integrand, weight) in enumerate((
                (T_rr, dV / r_safe),
                (comb, dV / r_safe ** 2),
                (comb, dV / r_safe ** 3),
            )):
                v0 = integrand[idx_c, cols]
                v1 = integrand[idx_c + 1, cols]
                vals = (v0 * (1.0 - frac) + v1 * frac) * inside
                partial = np.sum(vals * weight[None, :], axis=1)
                if k == 0:
                    a1 += partial
                elif k == 1:
                    a2 += partial
                else:
                    a3 += partial
        acc1[o], acc2[o], acc3[o] = a1, a2, a3

    d2 = (acc1[:, 2:] - 2.0 * acc1[:, 1:-1] + acc1[:, :-2]) / dt ** 2
    p_prime = d2 / c0 ** 2
    if include_near_field:
        d1 = (acc2[:, 2:] - acc2[:, :-2]) / (2.0 * dt)
        p_prime = p_prime - d1 / c0 + acc3[:, 1:-1]
    p_prime /= 4.0 * math.pi
    return p_prime, t_obs[1:-1]


