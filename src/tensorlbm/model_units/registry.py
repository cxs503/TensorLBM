"""Discovery of model units -- the analogue of TCLB ``src/models.R::get.models``.

Reference practice (extracted from the TCLB source at run time in
``tools/xval_m17991_model_dir_ci_unit.py``): the model list is *enumerated*
from the filesystem and git index, never hand-maintained::

    M1 = get.model.dirs("git ls-files | grep 'conf.mk$'")
    M2 = get.model.dirs("find models -name 'conf.mk'")
    M3 = union(M1, M2)

That union matters: a model that is only in the working tree (new, untracked)
still builds locally, and a model that is tracked but removed from the disk is
caught instead of silently vanishing from CI.  This module ports exactly that
rule, substituting ``model.toml`` for ``conf.mk``.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

from .manifest import MANIFEST_NAME, ManifestError, ModelUnit, load_unit

DEFAULT_ROOT = Path("models") / "lbm"


def _git_tracked_manifests(repo_root: Path) -> list[Path]:
    """``git ls-files`` half of the discovery union (empty if git is absent)."""
    try:
        out = subprocess.run(
            ["git", "ls-files", f"*{MANIFEST_NAME}"],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):  # pragma: no cover - no git binary
        return []
    if out.returncode != 0:
        return []
    return [repo_root / line.strip() for line in out.stdout.splitlines() if line.strip()]


def _filesystem_manifests(root: Path) -> list[Path]:
    """``find models -name model.toml`` half of the discovery union."""
    if not root.is_dir():
        return []
    return sorted(root.glob(f"*/{MANIFEST_NAME}"))


def manifest_paths(root: Path | str = DEFAULT_ROOT, *, repo_root: Path | None = None) -> list[Path]:
    """Return the discovered ``model.toml`` paths, union of git and filesystem."""
    root_path = Path(root)
    repo = Path(repo_root) if repo_root is not None else Path.cwd()
    found: dict[Path, None] = {}
    for path in _git_tracked_manifests(repo):
        # keep only manifests inside the requested root (git lists the whole repo)
        try:
            path.resolve().relative_to(root_path.resolve())
        except ValueError:
            continue
        found[path.resolve()] = None
    for path in _filesystem_manifests(root_path):
        found[path.resolve()] = None
    return sorted(found)


def discover(root: Path | str = DEFAULT_ROOT, *, repo_root: Path | None = None) -> list[ModelUnit]:
    """Discover all model units below ``root``, sorted by ``group/name``.

    Raises :class:`ManifestError` on a malformed unit and on a duplicate name,
    so a broken model directory fails the CI *plan* job for everybody rather
    than one matrix cell.
    """
    units = [load_unit(path) for path in manifest_paths(root, repo_root=repo_root)]
    seen: dict[str, Path] = {}
    for unit in units:
        if unit.unit_id in seen:
            raise ManifestError(
                f"duplicate model unit {unit.unit_id!r}: {seen[unit.unit_id]} and {unit.path}"
            )
        seen[unit.unit_id] = unit.path
    return units


def ci_units(units: list[ModelUnit]) -> list[ModelUnit]:
    """Units opted into the CI matrix (TCLB ``conf.mk`` ``TEST=TRUE``)."""
    return [u for u in units if u.ci]


def ci_matrix(units: list[ModelUnit], python: str = "python") -> dict[str, list[dict[str, str]]]:
    """GitHub-Actions matrix generated from the enumerated units.

    No unit name is ever written by hand in the workflow: the ``plan`` job runs
    this function and feeds ``fromJSON(needs.plan.outputs.matrix)``.
    """
    include = [
        {
            "unit": u.name,
            "group": u.group,
            "lattice": u.lattice,
            "dimension": str(u.dimension),
            "tier": u.tier,
            "cmd": f"PYTHONPATH=src {python} -m tensorlbm.model_units build-and-test --unit {u.name}",
        }
        for u in ci_units(units)
    ]
    return {"include": include}


def makefile_targets(units: list[ModelUnit], python: str = "python") -> str:
    """Generated Makefile fragment: ``make model-<name>`` per unit (TCLB ``CLB/<model>``)."""
    lines = [
        "# GENERATED by `python -m tensorlbm.model_units makefile` -- do not edit.",
        "# One build+test target per model directory (mirrors TCLB's CLB/<model>).",
        "",
        "MODEL_UNITS := " + " ".join(u.name for u in units),
        f"PYTHON ?= {python}",
        "MODEL_UNIT_ENV := PYTHONPATH=src",
        "",
        ".PHONY: model-units-build model-units-test model-units-list "
        + " ".join(f"model-{u.name}" for u in units),
        "",
        "model-units-build model-units-test model-units-list:",
        "\t$(MODEL_UNIT_ENV) $(PYTHON) -m tensorlbm.model_units $(patsubst model-units-%,%,$@)",
        "",
    ]
    for u in units:
        lines.append(f"model-{u.name}:")
        lines.append(
            f"\t$(MODEL_UNIT_ENV) $(PYTHON) -m tensorlbm.model_units build-and-test --unit {u.name}"
        )
        lines.append("")
    return "\n".join(lines)
