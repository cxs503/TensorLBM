#!/usr/bin/env python3
"""Figures + machine-generated tables for the elliptic-duct two-arm study.

Reads ``ibb_result_a8.json`` / ``ibb_result_a20.json`` / ``ibb_result_circle_a20.json``
(written by ``run_ibb.py``) and produces

* ``figures/ibb_two_arm.png`` — (a) normalised cross-section profiles vs the
  continuous-ellipse analytic parabola at a = 20, (b) theta_sQ / delta_eff for
  every arm, (c) the circular control case;
* ``ibb_tables.md`` — the result tables of the report, generated from the JSON
  (no number in the report is typed by hand).

Run: PYTHONPATH=<repo>/src python make_ibb_figures.py
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
FIGS = HERE / "figures"
FIGS.mkdir(exist_ok=True)

CASES = [
    ("ellipse a=8 b=4", "ibb_result_a8.json"),
    ("ellipse a=20 b=10", "ibb_result_a20.json"),
    ("circle R=20 (control)", "ibb_result_circle_a20.json"),
]


def load() -> list[dict]:
    arms: list[dict] = []
    for label, fn in CASES:
        p = HERE / fn
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        for r in d["arms"]:
            r["label"] = label
            arms.append(r)
    return arms


def tables(arms: list[dict]) -> str:
    lines = ["<!-- generated by make_ibb_figures.py; do not edit by hand -->", ""]
    lines += [
        "### T1 两臂对照（同一驱动、同一测量算子）",
        "",
        "| 案例 | 壁面格式 | 步数 | 收敛 | θ_nom [%] | θ_sQ [%] | δ_a^eff (格) | δ_b^eff (格) | a_fit−a | b_fit−b |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in arms:
        lines.append(
            f"| {r['label']} | {r['wall']} | {r['steps']} | {r['converged']} | "
            f"{r['theta_nom_pct']:.3f} | {r['theta_sQ_pct']:.3f} | "
            f"{r['delta_a_eff']:+.3f} | {r['delta_b_eff']:+.3f} | "
            f"{r['delta_a_fit']:+.3f} | {r['delta_b_fit']:+.3f} |"
        )
    lines += ["", "### T2 峰值/流量", "", "| 案例 | 壁面格式 | s^Q | Q/Q_ana | u_axis/U_max−1 [%] | 墙钟 [s] |",
              "|---|---|---|---|---|---|"]
    for r in arms:
        q_ana = math.pi * r["a"] * r["b"] * r["u_max_nom"] / 2.0
        lines.append(
            f"| {r['label']} | {r['wall']} | {r['s_Q']:.5f} | {r['Q']/q_ana:.5f} | "
            f"{r['u_axis_err_pct']:+.2f} | {r['wall_clock_s']:.1f} |"
        )
    return "\n".join(lines) + "\n"


def figure(arms: list[dict]) -> Path:
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.2))
    colors = {"halfway": "tab:red", "ibb": "tab:blue"}

    # (a) profiles at a=20
    ax = axes[0]
    sel = [r for r in arms if r["label"] == "ellipse a=20 b=10"]
    if sel:
        lam = np.array([b["lam"] for b in sel[0]["bins"]])
        u_ana = np.array([b["u_ana"] for b in sel[0]["bins"]])
        ax.plot(lam, u_ana / sel[0]["u_max_nom"], "k--", lw=2, label="analytic (continuous ellipse, s^Q)")
        for r in sel:
            u = np.array([b["u_num"] for b in r["bins"]])
            ax.plot(lam, u / r["u_max_nom"], "o-", ms=3, color=colors.get(r["wall"], "gray"),
                    label=f"{r['wall']} (θ_sQ={r['theta_sQ_pct']:.2f}%)")
        ax.set_xlabel("λ = (y/a)² + (z/b)²")
        ax.set_ylabel("u / U_max")
        ax.set_title("(a) a=20 b=10 elliptic duct")
        ax.legend(fontsize=7)

    # (b) metric bars
    ax = axes[1]
    labels = [f"{r['label'].split(' ')[0]} {r['wall']}" for r in arms]
    xs = np.arange(len(arms))
    ax.bar(xs - 0.2, [r["theta_sQ_pct"] for r in arms], 0.4, label="θ_sQ [%]", color="tab:purple")
    ax.bar(xs + 0.2, [r["delta_a_eff"] for r in arms], 0.4, label="δ_a^eff [cells]", color="tab:green")
    ax.set_xticks(xs)
    ax.set_xticklabels(labels, rotation=45, ha="right", fontsize=7)
    ax.axhline(3.0, color="k", ls=":", lw=1)
    ax.set_title("(b) shape error and wall offset")
    ax.legend(fontsize=7)

    # (c) circle control profiles
    ax = axes[2]
    sel = [r for r in arms if r["label"] == "circle R=20 (control)"]
    if sel:
        lam = np.array([b["lam"] for b in sel[0]["bins"]])
        u_ana = np.array([b["u_ana"] for b in sel[0]["bins"]])
        ax.plot(lam, u_ana / sel[0]["u_max_nom"], "k--", lw=2, label="analytic (s^Q)")
        for r in sel:
            u = np.array([b["u_num"] for b in r["bins"]])
            ax.plot(lam, u / r["u_max_nom"], "o-", ms=3, color=colors.get(r["wall"], "gray"),
                    label=f"{r['wall']} (θ_sQ={r['theta_sQ_pct']:.2f}%)")
        ax.set_xlabel("λ = r²/R²")
        ax.set_ylabel("u / U_max")
        ax.set_title("(c) circular control R=20")
        ax.legend(fontsize=7)

    fig.suptitle("Elliptic-duct Poiseuille: half-way bounce-back vs SDF interpolated bounce-back", fontsize=10)
    fig.tight_layout()
    out = FIGS / "ibb_two_arm.png"
    fig.savefig(out, dpi=140)
    return out


def main() -> None:
    arms = load()
    (HERE / "ibb_tables.md").write_text(tables(arms))
    p = figure(arms)
    print(f"wrote {p} and {HERE / 'ibb_tables.md'} ({len(arms)} arms)")


if __name__ == "__main__":
    main()