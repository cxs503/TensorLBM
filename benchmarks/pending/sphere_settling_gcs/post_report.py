#!/usr/bin/env python3
"""Build (and optionally post) the platform progress report.

The markdown body is ``docs/sphere_settling_gcs_20261107.md`` (generated by
``make_report.py`` from ``result.json``), so the report body contains no
hand-copied numbers.  Figures are downscaled before base64 encoding — the
platform rejects payloads above ~250 KB (known trap: silently 500s).
"""
from __future__ import annotations

import argparse
import base64
import io
import json
import os
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
DOC = REPO / "docs" / "sphere_settling_gcs_20261107.md"
FIGDIR = HERE / "figures"

CAPTIONS = {
    "fig1_settling_vs_stokes.png": "①沉降终速 vs 解析 Stokes：λ→0 与 1/R→0 外推",
    "fig2_force_series_oscillation.png": "②瞬时力时间序列与振荡幅度（2% 判据线）",
    "fig5_field_snapshot.png": "稳态中截面 u_x / |u| 云图 + 体素球轮廓 + 控制面 R+2.5",
    "fig3_instruments.png": "控制面半径独立性 + 精确动量平衡锚点 / 独立盒式 CV 仪器",
    "fig4_reynolds_scan.png": "Re 扫描（方法边界）",
}


def png_b64(path: Path, max_w: int = 620) -> str:
    from PIL import Image

    im = Image.open(path).convert("RGB")
    if im.width > max_w:
        im = im.resize((max_w, int(im.height * max_w / im.width)))
    buf = io.BytesIO()
    im.save(buf, format="PNG", optimize=True)
    return base64.b64encode(buf.getvalue()).decode()


def build(markdown: str, keys: list[str]) -> dict:
    figs = []
    for name in keys:
        p = FIGDIR / name
        if not p.exists():
            continue
        figs.append({"name": name, "caption": CAPTIONS.get(name, name), "png_base64": png_b64(p)})
    return {
        "title": "LBM 球面力法 G15 第三法：伽利略不变动能通量控制面（TensorLBM, IN14-D8）",
        "summary": (
            "交付与前两法（G12 壁面压力/摩擦、G15 逐链 MEM）方法论独立的第三类球面力估计器："
            "在包围物体的解析球面上积分原始二阶矩动能通量 Π=Σfcc。均匀背景零空间精确"
            "（∮n dA=0 至机器精度），采样面不接触壁面。10 项解析 pytest 通过；周期沉降槽中"
            "给出终速、瞬时力振荡幅度与方法边界，并量化了本库反弹边界在 τ≳5 的迁移率缺陷。"
            "未通过的预注册判据如实记为 FAIL。"
        ),
        "scenario_key": "lattice-boltzmann-sphere-force-gcs",
        "mission_id": 4981,
        "tags": ["TensorLBM", "LBM", "球面力法", "G15", "沉浸边界", "沉降", "验证"],
        "markdown": markdown,
        "figures": figs,
    }


def post(payload: dict, base: str, user: str, password: str) -> None:
    def api(method, path, body=None, tok=None):
        req = urllib.request.Request(
            base + path,
            method=method,
            data=json.dumps(body).encode() if body is not None else None,
        )
        req.add_header("Content-Type", "application/json")
        if tok:
            req.add_header("Authorization", "Bearer " + tok)
        try:
            with urllib.request.urlopen(req, timeout=120) as r:
                return r.status, json.loads(r.read() or b"{}")
        except urllib.error.HTTPError as e:
            return e.code, e.read()[:500]

    st, d = api("POST", "/auth/login", {"username": user, "password": password})
    assert st == 200, (st, d)
    tok = d["access_token"]
    size = len(json.dumps(payload))
    print(f"payload {size / 1024:.1f} KB")
    st, d = api("POST", "/tensor/reports", payload, tok)
    print("POST /tensor/reports ->", st, str(d)[:300])
    st, d = api("GET", f"/tensor/reports?mission_id={payload['mission_id']}", None, tok)
    if st == 200:
        items = d if isinstance(d, list) else d.get("items", d.get("reports", []))
        print("verify:", [(it.get("id"), it.get("title", "")[:40]) for it in items][:3])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--post", action="store_true")
    ap.add_argument("--out", default="/tmp/report.json")
    args = ap.parse_args()
    payload = build(
        DOC.read_text(),
        [
            "fig1_settling_vs_stokes.png",
            "fig2_force_series_oscillation.png",
            "fig5_field_snapshot.png",
        ],
    )
    Path(args.out).write_text(json.dumps(payload))
    print("wrote", args.out, f"{Path(args.out).stat().st_size / 1024:.1f} KB")
    if args.post:
        post(
            payload,
            os.environ["TENSOR_API_BASE"],
            os.environ["TENSOR_AGENT_USER"],
            os.environ["TENSOR_AGENT_PASS"],
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())