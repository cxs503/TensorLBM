def tbl(rws, cols, hdr):
    out = ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
    for r in rws:
        out.append(
            "| "
            + " | ".join(f"{r[c]:.6e}" if isinstance(r[c], float) else str(r[c]) for c in cols)
            + " |"
        )
    return "\n".join(out)


