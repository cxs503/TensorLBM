"""Render ``REPORT.md`` for the mcmp_stratified_poiseuille benchmark.

Every number in the rendered markdown comes from ``result.json`` (which is
itself assembled from the raw run records) — nothing is retyped.

Usage::

    python benchmarks/verified/mcmp_stratified_poiseuille/report.py
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RESULT = os.path.join(HERE, "result.json")
OUT = os.path.join(HERE, "REPORT.md")


def pct(x, nd=1):
    return f"{100 * x:+.{nd}f}%"


def main() -> int:
    r = json.load(open(RESULT))
    cells = r["cells"]
    walls = r["wall_calibration"]
    thr = r["thresholds"]
    ov = r["overall_verdict"]

    L = []
    L.append("# MCMP stratified Poiseuille — TensorBench record\n")
    L.append(f"Anchor: `{r['anchor']}`  ·  benchmark id `{r['benchmark']}`  ·  "
             f"status **verified** (see the verdict below)\n")
    L.append("Rendered from `result.json` by `report.py`; `result.json` is assembled from the raw "
             "run records under `artifacts/mcmp_stratified_poiseuille/records/` by `assemble.py` "
             "(`record_sha256` in the json). No number below is typed by hand.\n")
    L.append("## 1. Verdict\n")
    L.append(f"- Acceptance cells (u_eq=`viscous`, force_scheme=`guo`, G_12=-2.5, ny=25 and 33): "
             f"**{'PASS' if ov['acceptance_cells_ok'] else 'FAIL'}** "
             f"({ov['n_acceptance_cells_found']}/{ov['n_acceptance_cells_declared']} found)\n")
    L.append(f"- Gate: finite & steady & stratified, `|err Q_mix| < {thr['err_Q_mix_abs']:.0%}` "
             "against **both** viscosity rules and under the *measured* wall convention.\n")
    for c in cells:
        if c["tag"] in {t["tag"] for t in ov.get("hold_out", [])}:
            L.append(f"- Hold-out `{c['tag']}` (ny={c['ny']}): err {pct(c['errors_mixture']['err_Q_mix'])} "
                     f"(mixture rule) / {pct(c['errors_component']['err_Q_mix'])} (component rule); "
                     f"steady gate {'passed' if c['gates']['steady'] else 'not reached'} "
                     f"→ {'counts' if c['verdict']['gate_ok'] else 'does not count'} as acceptance.\n")
    L.append("\n## 2. Wall convention (control experiment)\n")
    L.append("Single-phase Poiseuille through the identical collision / streaming / bounce-back path "
             "(`run_sweep.py --mode walls`). The effective no-slip plane is whichever convention makes "
             "the error vanish — this decides the reference, it is not a preference.\n")
    L.append("| ny | tau | u_max err, H=ny-1 | Q err, H=ny-1 | u_max err, H=ny-2 | Q err, H=ny-2 |")
    L.append("|---|---|---|---|---|---|")
    for w in sorted(walls, key=lambda w: (w["ny"], w["tau"])):
        L.append(f"| {w['ny']} | {w['tau']:.2f} | {pct(w['H_ny_minus_1']['u_max_error_rel'],2)} | "
                 f"{pct(w['H_ny_minus_1']['Q_error_rel'],2)} | "
                 f"{pct(w['H_ny_minus_2']['u_max_error_rel'],2)} | "
                 f"{pct(w['H_ny_minus_2']['Q_error_rel'],2)} |")
    L.append("\nConclusion: the no-slip planes are **half-way** between the wall row and the first "
             "fluid row (`H = ny-2`), to 0.03–0.21 % in u_max and 0.06–0.30 % in Q over ny=25/33/49 "
             "and tau=1.0/0.75. The cell-centre convention (`H = ny-1`) is 4–8 % low and does not "
             "converge faster.\n")
    L.append("\n## 3. Two-phase flow rate (all configurations)\n")
    L.append("`err_Q_mix` = (Q_mix − Q_ref)/Q_ref with Q_mix = Σ_y (ρ₁u₁+ρ₂u₂)/(ρ₁+ρ₂); "
             "`hw` = the measured half-way wall convention; "
             "`comp` = per-layer component viscosity, `mixt` = density-weighted mixture viscosity.\n")
    L.append("| case | ny | G_12 | u_eq | force | steps | phi | steady | Q_mix | err hw/comp | err hw/mixt |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for c in sorted(cells, key=lambda c: (c["ny"], c["u_eq"], c["force_scheme"], c["steps"])):
        if "errors_mixture" not in c:
            L.append(f"| {c['tag']} | {c['ny']} | {c['G_12']:+.1f} | {c['u_eq']} | "
                     f"{c['force_scheme']} | {c['steps']} | – | – | DIVERGED | – | – |")
            continue
        L.append(f"| {c['tag']} | {c['ny']} | {c['G_12']:+.1f} | {c['u_eq']} | {c['force_scheme']} | "
                 f"{c['steps']} | {c['gates']['phi_contrast']:.2f} | "
                 f"{'yes' if c['gates']['steady'] else 'no'} | {c['Q_mix']:.4f} | "
                 f"{pct(c['errors_component']['err_Q_mix'])} | {pct(c['errors_mixture']['err_Q_mix'])} |")
    L.append("\nThe full four-column table (both wall conventions x both viscosity rules) is "
             "`artifacts/mcmp_stratified_poiseuille/analysis.json`, regenerated by "
             "`cases/mcmp_stratified_poiseuille/analyze.py`.\n")
    L.append("\n## 4. Acceptance cells\n")
    for c in cells:
        if "errors_mixture" not in c:
            continue
        if not (c["verdict"]["gate_ok"] or c["ny"] == 49):
            continue
        v = c["verdict"]
        L.append(f"### `{c['tag']}` (ny={c['ny']}, {c['steps']} steps)\n")
        L.append(f"- |err Q_mix| (mixture rule) = {pct(c['errors_mixture']['err_Q_mix'])} "
                 f"(threshold {thr['err_Q_mix_abs']:.0%}) → {'PASS' if v['flow_rate_ok'] else 'FAIL'}")
        L.append(f"- |err Q_mix| (component rule) = {pct(c['errors_component']['err_Q_mix'])} → "
                 f"{'PASS' if v['flow_rate_ok_vs_component_rule'] else 'FAIL'}")
        L.append(f"- per-layer split: lower {pct(c['errors_mixture']['err_Q_mix_lower'])}, "
                 f"upper {pct(c['errors_mixture']['err_Q_mix_upper'])} "
                 f"(threshold {thr['err_Q_mix_layer_abs']:.0%}) → {'PASS' if v['layer_ok'] else 'FAIL'}")
        L.append(f"- interface position: {pct(c['errors_mixture']['err_interface_rel'])} "
                 f"(threshold {thr['err_interface_rel_abs']:.0%}) → {'PASS' if v['interface_ok'] else 'FAIL'}")
        L.append(f"- spurious current ratio S/U = {c['spurious_ratio']:.3f} "
                 f"(threshold {thr['spurious_ratio']}) → {'PASS' if v['spurious_ok'] else 'FAIL (not an acceptance gate)'}")
        L.append(f"- mass drift ρ₁ {c['mass_drift_1'] if 'mass_drift_1' in c else 'n/a'}\n")
    L.append("\n## 5. Environment and provenance\n")
    for env in r["environment"]:
        L.append(f"- python {env[0]}, torch {env[1]}, {env[2]}")
    L.append(f"- spec: `spec.json` (declared thresholds and stopping rule), "
             f"experiment design: `docs/MCMP_STRATIFIED_POISEUILLE_SPEC.md`")
    L.append(f"- runner: `cases/mcmp_stratified_poiseuille/run_matrix.py`, `run_coupling.py`, "
             f"`run_sweep.py`; analysis: `analyze.py`; figures: `make_figures.py`")
    L.append(f"- tests: `tests/test_mcmp_stratified_poiseuille.py`")
    L.append(f"- record sha256: " + ", ".join(f"`{k}`" for k in sorted(r["record_sha256"])[:6]) + " …\n")
    with open(OUT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", OUT, len(L), "lines")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())