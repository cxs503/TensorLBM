"""Merge the sweep shards, emit the report tables and the figures.

Every number in ``docs/SQUEEZE_FILM_LBM_FIRST_PRINCIPLES_VERIFICATION.md`` is produced
here from ``results.json`` - no hand copying.  Run after ``run_compare.py``.

    python summarize.py
"""

from __future__ import annotations

import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
FIG = os.path.join(HERE, "figures")


def load():
    out = {"reference_selfcheck": {}, "sweep": []}
    for name in ("sweep_a.json", "sweep_b.json"):
        path = os.path.join(HERE, name)
        if not os.path.exists(path):
            continue
        d = json.load(open(path))
        out["meta"] = d.get("meta", {})
        out["sweep"].extend(d["sweep"])
    sc_path = os.path.join(HERE, "selfcheck.json")
    if os.path.exists(sc_path):
        sc = json.load(open(sc_path))
        out["reference_selfcheck"] = sc
    out["sweep"].sort(key=lambda r: r["h"])
    return out


def tables(d: dict) -> str:
    lines = []
    sc = d["reference_selfcheck"]
    lines.append("<!-- TABLE:SELFCHECK:START (generated by summarize.py) -->")
    if "thin_limit" in sc:
        t = sc["thin_limit"]
        lines.append("| reference self-check (thin limit) | value |")
        lines.append("|---|---|")
        lines.append(f"| geometry | a={t['a']}, h={t['h']}, h/a={t['h_over_a']:.4f} |")
        lines.append(f"| grid | nx={t['nx']}, ny={t['ny']} (dx=dy) |")
        lines.append(f"| converged / iterations | {t['converged']} / {t['iterations']} |")
        lines.append(f"| mass imbalance | {t['mass_imbalance_rel']:.2e} |")
        lines.append(f"| normal load (reference) | {t['normal_load_top']:.6e} |")
        lines.append(f"| pressure load (reference) | {t['pressure_load_top']:.6e} |")
        lines.append(f"| Reynolds asymptote | {t['reynolds_load']:.6e} |")
        lines.append(f"| deviation vs asymptote | {t['err_normal_vs_rey_pct']:+.2f} % |")
        lines.append("")
    if "grid_ny24" in sc:
        g = sc["grid_ny24"]
        lines.append("| reference grid level (a=16, h=6) | normal load | vs ny=16 |")
        lines.append("|---|---|---|")
        lines.append(f"| ny=16 | {sc['grid_ny16_ref_normal']:.6e} | 0.00 % |")
        lines.append(f"| ny=24 | {g['normal_load_top']:.6e} | {sc['grid_rel_diff_pct']:+.2f} % |")
        lines.append("")
    lines.append("<!-- TABLE:SELFCHECK:END -->")

    lines.append("")
    lines.append("<!-- TABLE:SWEEP:START (generated by summarize.py) -->")
    lines.append("| h | h/a | LBM ME gauge | LBM wall p-integral | N-S reference (normal) | "
                 "Reynolds asymptote | LBM vs N-S | LBM vs Reynolds | N-S vs Reynolds |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for r in d["sweep"]:
        e = r["err_pct"]
        lines.append(
            f"| {r['h']} | {r['h_over_a']:.3f} | {r['lbm']['force_gauge_top']:.6e} | "
            f"{r['lbm']['force_pressure_integral']:.6e} | {r['ref']['normal_load_top']:.6e} | "
            f"{r['reynolds_load']:.6e} | **{e['lbm_me_vs_ref_normal']:+.2f} %** | "
            f"{e['lbm_me_vs_reynolds']:+.2f} % | {e['ref_normal_vs_reynolds']:+.2f} % |")
    lines.append("<!-- TABLE:SWEEP:END -->")
    return "\n".join(lines)


def figures(d: dict) -> list:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    os.makedirs(FIG, exist_ok=True)
    made = []

    # ---- figure 1: pressure profile, three calibers ------------------------
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.2))
    for a, r in zip(ax, d["sweep"]):
        pass
    rec = [r for r in d["sweep"] if r["h"] == 6][0]
    x_lbm = np.asarray(rec["lbm"]["_fields"]["x"])
    p_lbm = np.asarray(rec["lbm"]["_fields"]["p"])[:, -1]           # wall row y=0
    x_ref = np.asarray(rec["ref"]["_fields"]["x"])
    p_ref = np.asarray(rec["ref"]["_fields"]["p_top"])
    a_pl = rec["h_over_a"]
    ax[0].plot(x_lbm, p_lbm, "o", ms=3.5, label="LBM (wall row y=0)")
    ax[0].plot(x_ref, p_ref, "-", lw=1.6, label="N-S reference (top wall)")
    ax[0].plot(x_ref, 6 * 0.1 * 0.005 * (16**2 - x_ref**2) / 6**3, "--",
               lw=1.2, label="Reynolds asymptote")
    ax[0].set_xlabel("x [lattice units, plate centre at 0]")
    ax[0].set_ylabel("p")
    ax[0].set_title(f"pressure across the film, a=16, h=6 (h/a={a_pl:.3f})")
    ax[0].legend(fontsize=8)
    ax[0].grid(alpha=0.3)

    ha = np.array([r["h_over_a"] for r in d["sweep"]])
    e_lbm_ref = np.array([r["err_pct"]["lbm_me_vs_ref_normal"] for r in d["sweep"]])
    e_lbm_rey = np.array([r["err_pct"]["lbm_me_vs_reynolds"] for r in d["sweep"]])
    e_ref_rey = np.array([r["err_pct"]["ref_normal_vs_reynolds"] for r in d["sweep"]])
    ax[1].axhline(0, color="k", lw=0.8)
    ax[1].plot(ha, e_lbm_rey, "s--", label="LBM vs Reynolds asymptote (old caliber)")
    ax[1].plot(ha, e_ref_rey, "^-.", label="N-S reference vs Reynolds asymptote")
    ax[1].plot(ha, e_lbm_ref, "o-", label="LBM vs N-S reference (verification)")
    ax[1].axhspan(-3, 3, color="tab:green", alpha=0.12, label="+-3 % acceptance band")
    ax[1].set_xlabel("h/a")
    ax[1].set_ylabel("relative deviation [%]")
    ax[1].set_title("the 12-37 % was the asymptote, not the solver")
    ax[1].legend(fontsize=8)
    ax[1].grid(alpha=0.3)
    fig.tight_layout()
    path = os.path.join(FIG, "fig_error_attribution.png")
    fig.savefig(path, dpi=135)
    plt.close(fig)
    made.append(path)

    # ---- figure 2: gap-wise velocity profile vs the lubrication parabola ---
    fig, ax = plt.subplots(figsize=(5.4, 4.2))
    y_u = np.asarray(rec["ref"]["_fields"]["y_u"])
    u_mid = np.asarray(rec["ref"]["_fields"]["u_mid"])
    y_lbm = np.asarray(rec["lbm"]["_fields"]["y"])
    u_lbm_mid = np.asarray(rec["lbm"]["_fields"]["ux"])[len(np.asarray(rec["lbm"]["_fields"]["x"])) // 2, :]
    ax.plot(u_mid, y_u, "-", lw=1.8, label="N-S reference")
    ax.plot(u_lbm_mid, y_lbm, "o", ms=4, label="LBM (centre column)")
    ax.set_xlabel("u [lattice units]")
    ax.set_ylabel("y across the film")
    ax.set_title("streamwise velocity, a=16, h=6")
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    path = os.path.join(FIG, "fig_velocity_profile.png")
    fig.savefig(path, dpi=135)
    plt.close(fig)
    made.append(path)
    return made


def main() -> int:
    d = load()
    d["tables_markdown"] = tables(d)
    json.dump(d, open(os.path.join(HERE, "results.json"), "w"), indent=1)
    print(d["tables_markdown"])
    for p in figures(d):
        print("figure:", p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())