#!/usr/bin/env python3
"""Generate the instruction-DSL conformance cases for ``run_cases.sh``.

Why generated: every expected number in ``cases/*/expect.conf`` is derived from
the same quantities the instruction file declares (``nu = (1/s - 1/2)/3``,
``k = 2*pi/nx``, ``H = ny - 2``), so no reference value is ever hand-typed into
a case.  Re-running this script after an intended behaviour change re-pins the
suite; ``git diff`` on ``expect.conf`` then shows exactly which claims moved.

Expected values are of two kinds:

* **regression pins** -- the SHA-256 of the exact instruction text.  They do not
  encode physics, they detect that the *text* the suite exercises changed.
* **analytical references** -- the closed-form result for the declarative
  problem (Taylor-Green decay, force-driven Poiseuille, one-momentum-unit-per
  -step forcing).  Tolerances are the owner acceptance band (3 % strict band,
  15 % unacceptable).

Usage::

    python3 make_cases.py            # (re)write cases/ and their expect.conf
"""

from __future__ import annotations

import hashlib
import math
import shutil
from pathlib import Path

from tensorlbm.instruction_dsl import D2Q9_SCHEME_INSTRUCTIONS as SCHEME

HERE = Path(__file__).resolve().parent
CASES = HERE / "cases"

RELAXATION = 1.8
NU = (1.0 / RELAXATION - 0.5) / 3.0  # lattice viscosity declared by s=1.8
CS2 = 1.0 / 3.0
TAU = 1.0 / RELAXATION

# owner acceptance: >15 % unacceptable, the strict band used here is 3 %
TOL_PHYSICS = 0.03
TOL_EXACT = 1e-10

HEADER = "# {name}: {desc}\n# expect.conf is generated by make_cases.py -- do not hand edit\n"


def write_case(name: str, desc: str, program: str, expect: list[str]) -> None:
    d = CASES / name
    d.mkdir(parents=True, exist_ok=True)
    text = program if program.endswith("\n") else program + "\n"
    (d / "program.lbm").write_text(text, encoding="utf-8")
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    lines = [HEADER.format(name=name, desc=desc).rstrip("\n"), "exit=0",
             f"eq.program_digest={digest}", *expect]
    (d / "expect.conf").write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_reject(name: str, desc: str, program: str, exit_code: int,
                 error_class: str, diagnostic: str) -> None:
    d = CASES / name
    d.mkdir(parents=True, exist_ok=True)
    text = program if program.endswith("\n") else program + "\n"
    (d / "program.lbm").write_text(text, encoding="utf-8")
    lines = [
        HEADER.format(name=name, desc=desc).rstrip("\n"),
        f"exit={exit_code}",
        f"error_class={error_class}",
        f"diagnostic={diagnostic}",
    ]
    (d / "expect.conf").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    if CASES.exists():
        shutil.rmtree(CASES)
    CASES.mkdir(parents=True)

    # ------------------------------------------------------------------ valid
    # v01: a uniform state must not generate flow; the scheme must be free of
    # spurious currents at machine precision.
    write_case(
        "v01_static_uniform",
        "uniform rho=1 at rest, 10 steps: no spurious velocity or kinetic energy",
        SCHEME + "domain nx=8 ny=8\ninit uniform rho=1.0 ux=0.0 uy=0.0\nrun steps=10\n",
        [f"abs.u_max=0:{1e-15:.1e}", "abs.kinetic_energy=0:1e-30", "eq.steps=10"],
    )

    # v02: one body-force step adds exactly g of momentum (Strang half steps),
    # so after n steps u = n*g to round-off, independent of the relaxation rates.
    g, n = 1e-6, 100
    write_case(
        "v02_force_unit_momentum",
        "body force gx=1e-6 for 100 steps: u_max = n*g exactly (momentum invariant)",
        SCHEME + (
            "domain nx=8 ny=8\ninit uniform rho=1.0 ux=0.0 uy=0.0\n"
            f"force gx={g} gy=0.0\nrun steps={n}\n"
        ),
        [f"approx.u_max={n * g:.12e}:{1e-8:.0e}", f"eq.steps={n}"],
    )

    # v03: Taylor-Green vortex, amplitude decays as A*exp(-2*nu*k^2*t) and the
    # kinetic energy as E0*exp(-4*nu*k^2*t) (Succi 2001; Krueger et al. 2017 ch.5).
    nx = ny = 32
    amp, steps = 0.05, 200
    k = 2.0 * math.pi / nx
    u_max_ref = amp * math.exp(-2.0 * NU * k * k * steps)
    ke_ref = 0.25 * amp * amp * math.exp(-4.0 * NU * k * k * steps)
    write_case(
        "v03_tg_decay_32",
        "Taylor-Green 32^2 A=0.05, 200 steps: u_max and KE against exp(-2nu k^2 t) decay",
        SCHEME + (
            f"domain nx={nx} ny={ny}\ninit taylor_green rho=1.0 amp={amp} mode=1\n"
            f"run steps={steps}\n"
        ),
        [
            f"approx.u_max={u_max_ref:.12e}:{TOL_PHYSICS}",
            f"approx.kinetic_energy={ke_ref:.12e}:{TOL_PHYSICS}",
            f"approx.nu={NU!r}:{TOL_EXACT:.0e}",
            f"eq.steps={steps}",
        ],
    )

    # v04: force-driven channel, half-way bounce-back walls in y.  The parabolic
    # profile has u_max = g*H^2/(8*nu) with the channel height H = ny-2.
    ny_c, steps_c, g_c = 22, 12000, 1e-5
    H = ny_c - 2
    u_max_poiseuille = g_c * H * H / (8.0 * NU)
    write_case(
        "v04_channel_poiseuille",
        "channel 8x22 walls y=1/2,ny-3/2 (H=ny-2), g=1e-5, 12000 steps: u_max = gH^2/(8nu)",
        SCHEME + (
            f"domain nx=8 ny={ny_c}\n"
            "boundary xmin=periodic xmax=periodic ymin=bounce_back ymax=bounce_back\n"
            f"init uniform rho=1.0 ux=0.0 uy=0.0\nforce gx={g_c} gy=0.0\nrun steps={steps_c}\n"
        ),
        [
            f"approx.u_max={u_max_poiseuille:.12e}:{TOL_PHYSICS}",
            f"approx.nu={NU!r}:{TOL_EXACT:.0e}",
            f"eq.steps={steps_c}",
            f"eq.nx=8",
            f"eq.ny={ny_c}",
        ],
    )

    # v05: lattice invariants reachable through the CLI (weights sum, sound
    # speed, viscosity from the declared relaxation).
    write_case(
        "v05_lattice_invariants",
        "scheme self-checks surfaced through the CLI: cs2=1/3, tau=1/s, nu=(tau-1/2)/3",
        SCHEME + "domain nx=8 ny=8\ninit uniform rho=1.0\nrun steps=1\n",
        [
            f"approx.cs2={CS2!r}:{TOL_EXACT:.0e}",
            f"approx.tau={TAU!r}:{TOL_EXACT:.0e}",
            f"approx.nu={NU!r}:{TOL_EXACT:.0e}",
            "eq.steps=1",
        ],
    )

    # ---------------------------------------------------------------- rejects
    # exit 2 = DSLSyntaxError, exit 3 = DSLSemanticError (see the CLI docstring)
    write_reject(
        "i01_unknown_instruction",
        "a word that is not an instruction must name the offender and the vocabulary",
        SCHEME + "domain nx=8 ny=8\nnonsense foo=1\ninit uniform\nrun steps=1\n",
        2, "DSLSyntaxError", "unknown instruction 'nonsense'",
    )
    write_reject(
        "i02_unknown_argument",
        "an argument outside the instruction's whitelist must list what is allowed",
        SCHEME + "domain nx=8 ny=8\ninit uniform rho=1.0 qq=1\nrun steps=1\n",
        2, "DSLSyntaxError", "unknown argument 'qq'",
    )
    write_reject(
        "i03_expression_not_executable",
        "instruction expressions are sandboxed: attribute access is not lowered",
        SCHEME.replace("polynomial X", "polynomial X.real", 1)
        + "domain nx=8 ny=8\ninit uniform\nrun steps=1\n",
        2, "DSLSyntaxError", "unsupported construct Attribute",
    )
    write_reject(
        "i04_relaxation_out_of_range",
        "s=2.5 would give a negative viscosity; the invariant guard must refuse it",
        SCHEME.replace("relaxation 0,0,0,1.8", "relaxation 0,0,0,2.5")
        + "domain nx=8 ny=8\ninit uniform\nrun steps=1\n",
        3, "DSLSemanticError", "outside (0, 2)",
    )
    write_reject(
        "i05_singular_moment_matrix",
        "duplicated moment polynomial makes M singular -> no invertible lowering",
        SCHEME.replace("polynomial Y", "polynomial X", 1)
        + "domain nx=8 ny=8\ninit uniform\nrun steps=1\n",
        3, "DSLSemanticError", "moment matrix is singular",
    )
    write_reject(
        "i06_equilibrium_loses_mass",
        "an equilibrium that does not recover rho is not an equilibrium",
        SCHEME.replace("equilibrium rho", "equilibrium 1.0", 1)
        + "domain nx=8 ny=8\ninit uniform\nrun steps=1\n",
        3, "DSLSemanticError", "does not recover",
    )
    write_reject(
        "i07_unsupported_boundary_mix",
        "a boundary layout the 2-D lowering cannot honour is refused, not approximated",
        SCHEME + "domain nx=8 ny=8\nboundary xmin=bounce_back\ninit uniform\nrun steps=1\n",
        3, "DSLSemanticError", "unsupported boundary mix",
    )
    write_reject(
        "i08_three_dimensional_stencil",
        "dim=3 stencil must be refused by the 2-D lowering instead of silently run",
        SCHEME.replace("dim=2", "dim=3")
        + "domain nx=8 ny=8\ninit uniform\nrun steps=1\n",
        3, "DSLSemanticError", "not supported by the 2-D lowering",
    )
    write_reject(
        "i09_mach_guard",
        "u=0.5 lattice units (Ma~0.87) is beyond the incompressible guard",
        SCHEME + "domain nx=8 ny=8\ninit uniform rho=1.0 ux=0.5\nrun steps=1\n",
        3, "DSLSemanticError", "mach guard",
    )
    write_reject(
        "i10_missing_run_instruction",
        "a program without run control cannot be executed",
        SCHEME + "domain nx=8 ny=8\ninit uniform\n",
        2, "DSLSyntaxError", "missing instruction: run",
    )
    write_reject(
        "i11_duplicate_instruction",
        "a second 'domain' line silently overriding the first is a defect, not a shorthand",
        SCHEME + "domain nx=8 ny=8\ndomain nx=16 ny=16\ninit uniform\nrun steps=1\n",
        2, "DSLSyntaxError", "duplicate instruction 'domain'",
    )
    write_reject(
        "i12_steps_below_one",
        "run steps=0 would produce a record that claims a run happened",
        SCHEME + "domain nx=8 ny=8\ninit uniform\nrun steps=0\n",
        3, "DSLSemanticError", "run steps must be >= 1",
    )

    names = sorted(p.name for p in CASES.iterdir() if p.is_dir())
    print(f"wrote {len(names)} cases into {CASES}")
    for n in names:
        print("  ", n)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())