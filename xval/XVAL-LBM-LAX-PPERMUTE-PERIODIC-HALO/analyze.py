"""Turn artifacts/result.json into table.csv + figures + a numbers digest.

Nothing is typed by hand: every number in REPORT.md comes from the digest
printed by this script (which reads only ``artifacts/result.json``).
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

HERE = Path(__file__).resolve().parent
ART = HERE / "artifacts"
FIG = HERE / "figures"

FLOOR = 1e-16  # log-scale floor for "exactly zero" points


def load():
    return json.loads((ART / "result.json").read_text())


def write_csv(d):
    rows = []
    for r in d["rows_2d"]:
        rows.append(dict(r, family="REF"))
    rows += d["rows_sweep"]
    rows += d["rows_3d"]
    keys = ["family", "arm", "axis", "ranks", "field", "seed", "n_steps", "wire",
            "rel_l2", "max_abs", "bitwise_equal", "n_cross", "halo_lane_planes_per_step",
            "staging_bytes", "halo_bytes_per_step", "wall_s"]
    with (ART / "table.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=keys, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k, "") for k in keys})
    return rows


def fig_2d(d):
    labels, vals, colors = [], [], []
    for r in d["rows_2d"]:
        if r["field"] != "asym" or r["seed"] != 0:
            continue
        labels.append(f"{r['arm']}\n{r['axis']}/n={r['ranks']}")
        vals.append(max(r["rel_l2"], FLOOR))
        colors.append("#c1121f" if r["arm"].startswith("REF-A") else
                      "#e09f3e" if r["arm"] in ("REF-B", "REF-C") else "#2a9d8f")
    fig, ax = plt.subplots(figsize=(max(8, 0.55 * len(labels)), 4.2))
    ax.bar(range(len(vals)), vals, color=colors)
    ax.set_yscale("log")
    ax.axhline(0.15, ls="--", c="k", lw=1, label="owner 15% line")
    ax.axhline(1e-12, ls=":", c="b", lw=1, label="exactness line 1e-12")
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=90, fontsize=7)
    ax.set_ylabel("rel L2 error vs single-domain GT")
    ax.set_title("2-D vivsim reference arms (D2Q9, 20 steps, asym field)")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "fig_2d_arms.png", dpi=140)
    plt.close(fig)


def fig_sweep(d):
    fig, ax = plt.subplots(figsize=(5.2, 4.0))
    for arm, style in (("REF-A", "o-"), ("REF-C", "s-"), ("REF-C+CS", "^-")):
        pts = [r for r in d["rows_sweep"] if r["arm"] == arm]
        if not pts:
            continue
        ax.plot([p["n_steps"] for p in pts], [max(p["rel_l2"], FLOOR) for p in pts],
                style, label=arm)
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("steps")
    ax.set_ylabel("rel L2 error vs GT")
    ax.axhline(0.15, ls="--", c="k", lw=1)
    ax.set_title("halo error is a persistent bias (y-slab ring, n=4)")
    ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / "fig_step_sweep.png", dpi=140)
    plt.close(fig)


def fig_3d(d):
    rows = [r for r in d["rows_3d"]]
    labels = [f"{r['arm']}\nn={r['ranks']}/{r['field']}/{r['wire']}" for r in rows]
    vals = [max(r["rel_l2"], FLOOR) for r in rows]
    colors = ["#2a9d8f" if r["arm"].startswith("GOT") else
              ("#8e44ad" if "W1FILL" in r["arm"] else "#c1121f") for r in rows]
    fig, ax = plt.subplots(figsize=(max(9, 0.6 * len(labels)), 4.2))
    ax.bar(range(len(vals)), vals, color=colors)
    ax.set_yscale("log")
    ax.axhline(0.15, ls="--", c="k", lw=1, label="owner 15% line")
    ax.set_xticks(range(len(labels)))
    ax.set_xticklabels(labels, rotation=90, fontsize=6.5)
    ax.set_ylabel("rel L2 vs whole-domain GT")
    ax.set_title("3-D GOT arm (real TensorLBM halo code, gloo on CPU)")
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(FIG / "fig_3d_got.png", dpi=140)
    plt.close(fig)


def digest(d, rows):
    out = ["# numbers digest (generated by analyze.py)", ""]
    out.append("## 2-D vivsim arms (20 steps)")
    out.append("| arm | axis | n | field | seed | rel_l2 | max_abs | exact |")
    out.append("|---|---|---|---|---|---|---|---|")
    for r in d["rows_2d"]:
        out.append(f"| {r['arm']} | {r['axis']} | {r['ranks']} | {r['field']} | {r['seed']} | "
                   f"{r['rel_l2']:.3e} | {r['max_abs']:.3e} | {r['bitwise_equal']} |")
    out.append("\n## step sweep (axis=y, n=4, asym seed 0)")
    out.append("| arm | steps | rel_l2 |")
    out.append("|---|---|---|")
    for r in d["rows_sweep"]:
        out.append(f"| {r['arm']} | {r['n_steps']} | {r['rel_l2']:.3e} |")
    out.append("\n## 3-D GOT / CONTROL arms")
    out.append("| arm | n | field | seed | wire | rel_l2 | max_abs | bitwise | KE got | KE gt | lanes/step | halo bytes/step |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in d["rows_3d"]:
        out.append(f"| {r['arm']} | {r['ranks']} | {r['field']} | {r['seed']} | {r['wire']} | "
                   f"{r['rel_l2']:.3e} | {r['max_abs']:.3e} | {r['bitwise_equal']} | "
                   f"{r.get('ke_got', 0):.6e} | {r.get('ke_gt', 0):.6e} | "
                   f"{r['halo_lane_planes_per_step']} | {r['halo_bytes_per_step']} |")

    def worst(pred):
        sel = [r for r in d["rows_2d"] + d["rows_3d"] if pred(r)]
        return max(sel, key=lambda r: r["rel_l2"]) if sel else None

    rows_a = [r for r in d["rows_2d"] if r["arm"] == "REF-A"]
    rows_c = [r for r in d["rows_2d"] if r["arm"] == "REF-C"]
    rows_cs = [r for r in d["rows_2d"] if r["arm"] == "REF-CS"]
    got = [r for r in d["rows_3d"] if r["arm"] == "GOT" and r["tree"] if False] if False else \
        [r for r in d["rows_3d"] if r["arm"] == "GOT"]
    w1 = [r for r in d["rows_3d"] if "W1FILL" in r["arm"]]
    ctl = [r for r in d["rows_3d"] if r["arm"] == "CONTROL-LANE"]
    fp16 = [r for r in d["rows_3d"] if r["wire"] == "fp16"]
    out.append("\n## headline aggregates")
    out.append(f"* REF-A (literal port) rel_l2 range: {min(r['rel_l2'] for r in rows_a):.3e} .. "
               f"{max(r['rel_l2'] for r in rows_a):.3e}")
    out.append(f"* REF-C (plane+pair fixed) rel_l2 range: {min(r['rel_l2'] for r in rows_c):.3e} .. "
               f"{max(r['rel_l2'] for r in rows_c):.3e}")
    out.append(f"* REF-CS (+diagonal compensation) rel_l2 range: "
               f"{min(r['rel_l2'] for r in rows_cs):.3e} .. {max(r['rel_l2'] for r in rows_cs):.3e} "
               f"(all zero: {all(r['bitwise_equal'] for r in rows_cs)})")
    w1f = [r for r in w1 if r["ranks"] == 1]
    if w1f:
        out.append(f"* GOT world=1 with periodic ghost fill: rel_l2={w1f[0]['rel_l2']:.3e} "
                   f"bitwise={w1f[0]['bitwise_equal']} (validates the CPU stream substitute)")
    w1n = [r for r in w1 if r["ranks"] == 1]
    out.append(f"* GOT world=1 with the class's own single-rank halo branch: "
               f"rel_l2={[r['rel_l2'] for r in d['rows_3d'] if r['arm']=='GOT' and r['ranks']==1]}")
    if got:
        out.append(f"* GOT (2/4 ranks, real P2P) rel_l2 range: {min(r['rel_l2'] for r in got):.3e} .. "
                   f"{max(r['rel_l2'] for r in got):.3e}; bitwise everywhere: "
                   f"{all(r['bitwise_equal'] for r in got)}")
    if ctl:
        out.append(f"* CONTROL-LANE (swapped lane tables) rel_l2: "
                   f"{ctl[0]['rel_l2']:.3e} (must be >> GOT)")
    if fp16:
        out.append(f"* fp16 wire rel_l2: {[round(r['rel_l2'],6) for r in fp16]}")
    (ART / "digest.md").write_text("\n".join(out) + "\n")
    return "\n".join(out)


def main():
    FIG.mkdir(exist_ok=True)
    d = load()
    rows = write_csv(d)
    fig_2d(d)
    fig_sweep(d)
    fig_3d(d)
    txt = digest(d, rows)
    print(txt)


if __name__ == "__main__":
    main()