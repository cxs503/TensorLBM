#!/usr/bin/env python3
"""Figure for the m17664 board audit of m17603 (Inamuro wet-node XVAL).

Panels
  (a) concentration field at step 12000: auditor re-run through
      tensorlbm.boundary.inamuro_wetnode (left), the freshly compiled upstream
      OSS reference (middle — rebuilt in this audit, sha256-matched), and the
      pointwise absolute difference on a log colour scale (right);
  (b) deviation vs the reference at the four graded checkpoints (rel L2, rel
      Linf, log scale) against the 15 % acceptance line, plus the control probe
      (scalar Dirichlet closure removed) to show the metric is not vacuous.
Data: docs/board_audit/m17664/audit_fields.npz, audit.json (regenerated by
independent_audit.py), and the archived reference fields.
"""
from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

HERE = Path(__file__).resolve().parent
AUDIT = json.loads((HERE / "audit.json").read_text())
FIELDS = np.load(HERE / "audit_fields.npz")
REF_DIR = Path("/tmp/audit17664/oss/run/film_inamuro")

rows = {r["step"]: r for r in AUDIT["A3_A4_fresh_run"]["rows"]}
step = 12000
got = FIELDS[f"got_{step}"]
ref = np.loadtxt(REF_DIR / f"film_inamuro{step:07d}.dat").T

fig = plt.figure(figsize=(13.0, 7.6), constrained_layout=True)
gs = fig.add_gridspec(2, 3, height_ratios=[1.35, 1.0])

ax = fig.add_subplot(gs[0, 0])
im = ax.imshow(got, origin="lower", cmap="inferno", aspect="auto")
ax.set_title(f"TensorLBM (auditor re-run), step {step}", fontsize=10)
ax.set_xlabel("x [lattice]"); ax.set_ylabel("y [lattice]")
fig.colorbar(im, ax=ax, fraction=0.035, pad=0.02, label="c")

ax = fig.add_subplot(gs[0, 1])
im = ax.imshow(ref, origin="lower", cmap="inferno", aspect="auto")
ax.set_title("upstream film_inamuro.cpp (fresh g++ -O2 run)", fontsize=10)
ax.set_xlabel("x [lattice]")
fig.colorbar(im, ax=ax, fraction=0.035, pad=0.02, label="c")

ax = fig.add_subplot(gs[0, 2])
diff = np.abs(got - ref)
im = ax.imshow(np.maximum(diff, 1e-18), origin="lower", cmap="viridis",
               aspect="auto", norm=matplotlib.colors.LogNorm(vmin=1e-18, vmax=diff.max()))
ax.set_title(f"|got - ref|, max {diff.max():.2e}", fontsize=10)
ax.set_xlabel("x [lattice]")
fig.colorbar(im, ax=ax, fraction=0.035, pad=0.02, label="|Δc|")

ax = fig.add_subplot(gs[1, :])
steps = sorted(rows)
l2 = [rows[s]["rel_l2_vs_fresh_oss"] for s in steps]
linf = [rows[s]["rel_linf_vs_fresh_oss"] for s in steps]
ax.semilogy(steps, l2, "o-", label="rel L2 vs OSS reference", lw=1.8)
ax.semilogy(steps, linf, "s--", label="rel Linf vs OSS reference", lw=1.4)
ctl = AUDIT["A3_A4_fresh_run"]["control_probe_A5"]
ax.semilogy([1000], [ctl["rel_l2_at_step_1000"]], "X", ms=13, color="crimson",
            label="control probe: scalar Dirichlet closure removed (step 1000)")
ax.axhline(0.15, color="k", ls=":", lw=1.2, label="owner acceptance 15 %")
ax.set_xscale("log")
ax.set_xlabel("LBM step"); ax.set_ylabel("relative deviation")
ax.set_title("deviation vs the executed upstream reference — flat at 3-5e-11 over 12000 steps;\n"
             "removing the closure moves the metric by 10 orders of magnitude (metric is not vacuous)",
             fontsize=10)
ax.grid(alpha=0.3, which="both"); ax.legend(fontsize=8, loc="center left")
ax.set_ylim(1e-12, 3.0)

fig.suptitle("m17603 XVAL-LBM-ANTI-BOUNCE-BACK-INAMURO-WETNODE — board re-verification (m17664)",
             fontsize=11)
out = HERE / "fig_audit_m17664.png"
fig.savefig(out, dpi=130)
print("wrote", out, out.stat().st_size)