from __future__ import annotations

import json
import sys
from pathlib import Path


def _f(value, fmt="{:.4f}", dash="—") -> str:
    if value is None:
        return dash
    if isinstance(value, bool):
        return "yes" if value else "no"
    try:
        return fmt.format(value)
    except (TypeError, ValueError):
        return str(value)


def _pct(value, fmt="{:.2f}") -> str:
    if value is None:
        return "—"
    return fmt.format(value) + " %"


def _lt(value, threshold: float) -> str:
    if value is None:
        return "—"
    return "**yes**" if abs(value) < threshold else "**NO**"


def _stability_appendix(report: dict) -> dict:
    """Load ``stability_re200_{mrt,trt}.json`` next to the report, if present."""
    src = report.get("report_json") or report.get("_src_path") or ""
    base = Path(src).parent if src else Path(".")
    out: dict = {}
    for coll in ("mrt", "trt"):
        p = base / f"stability_re200_{coll}.json"
        if not p.exists():
            continue
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
        except json.JSONDecodeError:  # pragma: no cover
            continue
        rows = data.get("collisions", {}).get(coll, {})
        if rows:
            out[coll] = rows
    return out


