#!/usr/bin/env python3
"""Provenance script for the D3Q19 BGK analytic-verification thresholds.

Every published number in ``docs/lbm_analytic_verification_r1.md`` is produced
here by calling the **test-module functions themselves**
(``tests/test_lbm_verification.py``) — the same code path the assertions use —
so the document cannot drift from what CI checks.  No case is re-implemented:
the canonical cases are exactly the default arguments of those functions, and
the refinement studies only pass ``nx`` / ``ny`` / ``steps`` / ``tau`` keywords
through.

    python scripts/verify_lbm_analytic_convergence.py

Writes (all regenerated by the run, nothing hand-edited):

    artifacts/lbm_analytic_verification/convergence.json   every number below
    artifacts/lbm_analytic_verification/convergence.png   figure for the doc
    artifacts/lbm_analytic_verification/tables.md         markdown tables

Exit status is non-zero if a canonical case exceeds the test tolerance, if a
refinement study does not converge, or if a negative control is *not* detected
— the script is a gate, not a printer.
"""

from __future__ import annotations

import json
import math
import os
import sys
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import torch  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "tests"))

import test_lbm_verification as tv  # noqa: E402

OUT = ROOT / "artifacts" / "lbm_analytic_verification"

SHEAR_GRIDS = (16, 32, 64)
CHANNEL_GRIDS = (8, 12, 16)
CHANNEL_STEPS = 2000  # ny=16 的 Couette 瞬态在 1000 步未完全衰减（见 §6）


def _pct(err: float) -> float:
    """Absolute relative error in percent."""
    return abs(err) * 100.0


def _order(coarse: float, fine: float, ratio: float) -> float:
    """Observed convergence order between two grids of spacing ratio ``ratio``."""
    if fine <= 0.0 or coarse <= 0.0:
        return float("nan")
    return math.log(coarse / fine) / math.log(ratio)


def main() -> int:
    torch.set_num_threads(1)
    OUT.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    dev = tv._device()
    default_dtype = torch.get_default_dtype()

    data: dict = {
        "device": str(dev),
        "dtype": str(default_dtype).replace("torch.", ""),
        "machine": os.uname().machine,
        "rel_tol_pct": tv.REL_TOL * 100.0,
        "canonical": {},
        "shear": [],
        "poiseuille": [],
        "friction": [],
        "couette": [],
        "steady_budget": {},
        "controls": {},
        "runtime_s": None,
    }

    # -- 1. canonical cases: exactly what the tests assert (default args) -----
    canon_a = tv.shear_wave_case(dev)
    data["canonical"]["A_shear_wave"] = {
        "nx": 64,
        "nu_measured": canon_a["nu_measured"],
        "nu_exact": canon_a["nu_expected"],
        "err_pct": _pct(canon_a["rel_err"]),
    }
    canon_b = tv.couette_case(dev)
    data["canonical"]["B_couette"] = {"ny": 12, "err_pct": _pct(canon_b["rel_err"])}
    canon_c = tv.poiseuille_case(dev)
    data["canonical"]["C_poiseuille"] = {
        "ny": 12,
        "u_max_num": canon_c["u_max_num"],
        "u_max_exact": canon_c["u_max_exact"],
        "err_pct": _pct(canon_c["rel_err"]),
    }
    canon_d = tv.friction_case(dev)
    data["canonical"]["D_friction"] = {
        "ny": 12,
        "cf_num": canon_d["cf_num"],
        "cf_exact": canon_d["cf_exact"],
        "err_pct": _pct(canon_d["rel_err"]),
    }
    for name, rec in data["canonical"].items():
        print(f"[canonical] {name:<14} err={rec['err_pct']:.3e}%", flush=True)

    # -- 2. case A: shear-wave dispersion order (float64, round-off free) ----
    torch.set_default_dtype(torch.float64)
    for nx in SHEAR_GRIDS:
        r = tv.shear_wave_case(dev, nx=nx)
        data["shear"].append(
            {
                "nx": nx,
                "kdx": 2.0 * math.pi / nx,
                "nu_measured": r["nu_measured"],
                "nu_exact": r["nu_expected"],
                "err_pct": _pct(r["rel_err"]),
            }
        )
        print(
            f"[A/f64] nx={nx:3d} nu={r['nu_measured']:.12f} err={_pct(r['rel_err']):.3e}%",
            flush=True,
        )
    torch.set_default_dtype(default_dtype)
    s = data["shear"]
    data["shear_order"] = [
        _order(s[i]["err_pct"], s[i + 1]["err_pct"], s[i + 1]["nx"] / s[i]["nx"]) for i in range(2)
    ]
    print(f"[A] observed order {['%.2f' % o for o in data['shear_order']]}", flush=True)

    # -- 3. channel cases: height refinement (num = 2000 steps, steady) ------
    for ny in CHANNEL_GRIDS:
        p = tv.poiseuille_case(dev, ny=ny, steps=CHANNEL_STEPS)
        f = tv.friction_case(dev, ny=ny, steps=CHANNEL_STEPS)
        c = tv.couette_case(dev, ny=ny, steps=CHANNEL_STEPS)
        data["poiseuille"].append(
            {
                "ny": ny,
                "height": p["height"],
                "body_force": p["body_force"],
                "u_max_num": p["u_max_num"],
                "u_max_exact": p["u_max_exact"],
                "err_pct": _pct(p["rel_err"]),
                "u_num": p["u_num"],
                "u_exact": p["u_exact"],
            }
        )
        data["friction"].append(
            {
                "ny": ny,
                "u_wall": f["u_wall"],
                "cf_num": f["cf_num"],
                "cf_exact": f["cf_exact"],
                "err_pct": _pct(f["rel_err"]),
            }
        )
        data["couette"].append(
            {"ny": ny, "err_pct": _pct(c["rel_err"]), "u_num": c["u_num"], "u_exact": c["u_exact"]}
        )
        print(
            f"[C] ny={ny:2d} peak={_pct(p['rel_err']):.4f}%   "
            f"[D] ny={ny:2d} cf={_pct(f['rel_err']):.3e}%   "
            f"[B] ny={ny:2d} prof={_pct(c['rel_err']):.3e}%",
            flush=True,
        )

    pny = data["poiseuille"]
    data["poiseuille_order"] = [
        _order(
            pny[i]["err_pct"],
            pny[i + 1]["err_pct"],
            pny[i + 1]["height"] / pny[i]["height"],
        )
        for i in range(len(pny) - 1)
    ]
    print(f"[C] observed order {['%.2f' % o for o in data['poiseuille_order']]}", flush=True)

    # -- 4. is the asserted 1000-step budget really steady at ny=12? ---------
    for name, fn in (("B_couette", tv.couette_case), ("D_friction", tv.friction_case)):
        short = fn(dev, ny=12, steps=1000)["rel_err"]
        long = fn(dev, ny=12, steps=CHANNEL_STEPS)["rel_err"]
        data["steady_budget"][name] = {
            "err_1000_pct": _pct(short),
            "err_2000_pct": _pct(long),
            "ratio": abs(_pct(long) / _pct(short)) if short else float("nan"),
        }
        print(f"[budget] {name}: 1000={_pct(short):.3e}% 2000={_pct(long):.3e}%", flush=True)

    # -- 5. negative controls: do the 1 % thresholds actually discriminate? --
    nu_tau1 = next(x["nu_measured"] for x in data["shear"] if x["nx"] == 64)
    torch.set_default_dtype(torch.float64)
    r_tau = tv.shear_wave_case(dev, tau=1.05)
    torch.set_default_dtype(default_dtype)
    drift_pct = abs(r_tau["nu_measured"] - nu_tau1) / nu_tau1 * 100.0
    r_nobb = tv.couette_case(dev, ny=12, bounce_back=False)
    data["controls"] = {
        "tau_shift": {
            "nu_tau_1p05": r_tau["nu_measured"],
            "nu_tau_1p00": nu_tau1,
            "deviation_pct": drift_pct,
            "tolerance_pct": tv.REL_TOL * 100.0,
        },
        "no_bounce_back": {
            "couette_err_pct": _pct(r_nobb["rel_err"]),
            "tolerance_pct": tv.REL_TOL * 100.0,
        },
    }
    print(
        f"[ctrl] tau=1.05 deviation={drift_pct:.3f}%   "
        f"no-bounce-back Couette err={_pct(r_nobb['rel_err']):.3f}%",
        flush=True,
    )

    data["runtime_s"] = round(time.time() - t0, 1)
    (OUT / "convergence.json").write_text(json.dumps(data, indent=2), encoding="utf-8")

    # -- figure --------------------------------------------------------------
    fig, axes = plt.subplots(1, 3, figsize=(13.6, 4.2))
    ax = axes[0]
    kdx = [x["kdx"] for x in data["shear"]]
    err = [max(x["err_pct"], 1e-12) for x in data["shear"]]
    ax.loglog(kdx, err, "o-", label=r"$|\nu_{num}-\nu_{exact}|/\nu_{exact}$ (float64)")
    ax.loglog(kdx, [err[0] * (k / kdx[0]) ** 2 for k in kdx], "k--", lw=1, label=r"slope 2 ($k^2$)")
    ax.loglog(kdx, [err[0] * (k / kdx[0]) ** 4 for k in kdx], "k:", lw=1, label=r"slope 4 ($k^4$)")
    ax.axhline(tv.REL_TOL * 100.0, color="r", ls=":", lw=1, label="test tolerance (1%)")
    ax.set_xlabel(r"$k\,\Delta x$")
    ax.set_ylabel("relative error [%]")
    ax.set_title(r"(a) shear-wave viscosity, $\tau=1$")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=7)

    ax = axes[1]
    ax.semilogy(
        [p["ny"] for p in data["poiseuille"]],
        [p["err_pct"] for p in data["poiseuille"]],
        "s-",
        label="Poiseuille profile (C)",
    )
    ax.semilogy(
        [f["ny"] for f in data["friction"]],
        [f["err_pct"] for f in data["friction"]],
        "d-",
        label=r"wall friction $C_f$ (D)",
    )
    ax.semilogy(
        [c["ny"] for c in data["couette"]],
        [c["err_pct"] for c in data["couette"]],
        "^--",
        label="Couette profile (B)",
    )
    ax.axhline(tv.REL_TOL * 100.0, color="r", ls=":", lw=1, label="test tolerance (1%)")
    ax.set_xlabel(r"channel nodes $n_y$")
    ax.set_ylabel("relative error [%]")
    ax.set_title(f"(b) channel cases vs analytic ({CHANNEL_STEPS} steps)")
    ax.grid(True, which="both", alpha=0.3)
    ax.legend(fontsize=7)

    ax = axes[2]
    ref = next(p for p in data["poiseuille"] if p["ny"] == 12)
    y = list(range(1, ref["ny"] - 1))
    ax.plot(y, ref["u_exact"], "k-", lw=2, label=r"analytic $G(y-y_{w1})(y_{w2}-y)/2\nu$")
    ax.plot(y, ref["u_num"], "o", ms=5, mfc="none", label=r"LBM, $n_y=12$")
    ax.set_xlabel(r"$y$ [lattice]")
    ax.set_ylabel(r"$u_x$ [lattice]")
    ax.set_title(f"(c) Poiseuille profile, err {ref['err_pct']:.3f}%")
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=7)

    fig.suptitle(
        f"TensorLBM D3Q19 BGK analytic verification "
        f"({data['dtype']} asserted, {data['device']}, {data['machine']})",
        fontsize=10,
    )
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(OUT / "convergence.png", dpi=130)
    print("wrote", OUT / "convergence.png", flush=True)

    # -- markdown tables (zero hand-copy into the doc) -----------------------
    lines = [
        "<!-- generated by scripts/verify_lbm_analytic_convergence.py: do not edit -->",
        "",
        f"Device `{data['device']}`, asserted dtype `{data['dtype']}`, "
        f"machine `{data['machine']}`, test tolerance {data['rel_tol_pct']:g} %.",
        "",
        "| case | analytic quantity | numerical | analytic | rel. error |",
        "|---|---|---|---|---|",
        f"| A `nx=64, 100 steps` | $\\nu=(\\tau-\\frac12)/3$ | {canon_a['nu_measured']:.9f} | "
        f"{canon_a['nu_expected']:.9f} | {_pct(canon_a['rel_err']):.3e} % |",
        f"| C `n_y=12, 1000 steps` | $u_{{peak}}$ | {canon_c['u_max_num']:.8f} | "
        f"{canon_c['u_max_exact']:.8f} | {_pct(canon_c['rel_err']):.4f} % |",
        f"| D `n_y=12, 1000 steps` | $C_f=2\\nu/(L U)$ | {canon_d['cf_num']:.8f} | "
        f"{canon_d['cf_exact']:.8f} | {_pct(canon_d['rel_err']):.3e} % |",
        f"| B `n_y=12, 1000 steps` | $u_x(y)$ profile | — | — | {_pct(canon_b['rel_err']):.3e} % |",
        "",
        "| case A: nx | $k\\Delta x$ | ν measured (float64) | ν exact | rel. error |",
        "|---|---|---|---|---|",
    ]
    for x in data["shear"]:
        lines.append(
            f"| {x['nx']} | {x['kdx']:.4f} | {x['nu_measured']:.12f} | "
            f"{x['nu_exact']:.9f} | {x['err_pct']:.3e} % |"
        )
    lines += [
        "",
        "| case C: $n_y$ | $H$ | $u_{peak}$ numerical | $u_{peak}$ analytic | rel. error |",
        "|---|---|---|---|---|",
    ]
    for p in data["poiseuille"]:
        lines.append(
            f"| {p['ny']} | {p['height']} | {p['u_max_num']:.8f} | "
            f"{p['u_max_exact']:.8f} | {p['err_pct']:.4f} % |"
        )
    lines += [
        "",
        "| case D: $n_y$ | $u$ first node | $C_f$ numerical | $C_f$ analytic | rel. error |",
        "|---|---|---|---|---|",
    ]
    for f in data["friction"]:
        lines.append(
            f"| {f['ny']} | {f['u_wall']:.8f} | {f['cf_num']:.8f} | "
            f"{f['cf_exact']:.8f} | {f['err_pct']:.3e} % |"
        )
    lines += ["", "| case B: $n_y$ | profile rel. error |", "|---|---|"]
    for cse in data["couette"]:
        lines.append(f"| {cse['ny']} | {cse['err_pct']:.3e} % |")
    lines += ["", "| steady budget (n_y=12) | 1000 steps | 2000 steps |", "|---|---|---|"]
    for name, rec in data["steady_budget"].items():
        lines.append(f"| {name} | {rec['err_1000_pct']:.3e} % | {rec['err_2000_pct']:.3e} % |")
    ctrl = data["controls"]
    lines += [
        "",
        "| negative control | measured signal | test tolerance |",
        "|---|---|---|",
        f"| A run at $\\tau=1.05$ vs $\\nu(\\tau=1)$ | "
        f"{ctrl['tau_shift']['deviation_pct']:.3f} % | 1 % → detected |",
        f"| B Couette with bounce-back disabled | "
        f"{ctrl['no_bounce_back']['couette_err_pct']:.3f} % | 1 % → detected |",
        "",
        f"Runtime {data['runtime_s']} s on one CPU thread, "
        f"observed order: A {['%.2f' % o for o in data['shear_order']]}, "
        f"C {['%.2f' % o for o in data['poiseuille_order']]}.",
        "",
    ]
    (OUT / "tables.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote", OUT / "tables.md", flush=True)

    # -- gate ----------------------------------------------------------------
    tol = data["rel_tol_pct"]
    problems = [
        f"canonical {name} {rec['err_pct']:.3e} % over tolerance"
        for name, rec in data["canonical"].items()
        if rec["err_pct"] >= tol
    ]
    problems += [
        f"case {tag} ny={rec['ny']} {rec['err_pct']:.4f} % over tolerance"
        for tag, series in (
            ("C", data["poiseuille"]),
            ("D", data["friction"]),
            ("B", data["couette"]),
        )
        for rec in series
        if rec["err_pct"] >= tol
    ]
    if not data["poiseuille"][0]["err_pct"] > data["poiseuille"][-1]["err_pct"]:
        problems.append("case C error did not decrease with channel refinement")
    if min(data["shear_order"]) < 2.0:
        problems.append("shear-wave order below 2")
    if min(data["poiseuille_order"]) < 1.5:
        problems.append("Poiseuille error does not converge at ~2nd order in H")
    if ctrl["tau_shift"]["deviation_pct"] <= tol:
        problems.append("tau-shift control not detected by the tolerance")
    if ctrl["no_bounce_back"]["couette_err_pct"] <= tol:
        problems.append("missing-bounce-back control not detected by the tolerance")

    if problems:
        print("\nFAIL: " + "; ".join(problems), file=sys.stderr)
        return 1
    print(f"\nOK: canonical cases < {tol:g} %, refinement converges, controls detected.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
