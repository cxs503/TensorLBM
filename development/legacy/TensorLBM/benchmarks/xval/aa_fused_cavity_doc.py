"""Generate ``docs/xval_aa_pattern_cavity_acceptance.md`` from the artifacts.

Every number in the generated document is read from
``artifacts/xval_aa_pattern/cavity_verdict.json`` / ``cavity_accept_<idx>.json``
at build time -- nothing is transcribed by hand, so a re-run of the sweep cannot
leave the prose stale.

Run after the sweep + ``aa_fused_cavity_verdict.py``:
``python benchmarks/xval/aa_fused_cavity_doc.py``
"""

