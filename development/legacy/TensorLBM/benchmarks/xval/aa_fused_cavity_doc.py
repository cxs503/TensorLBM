def _f(x, fmt="{:.4f}"):
    return "n/a" if x is None else fmt.format(x)


def residual_series(tasks: dict) -> dict:
    """``{L: [(step, residual, L2_u_full, mass_drift), ...]}`` from the histories."""
    out = {}
    for t in tasks.values():
        if t.get("task") != "cavity" or t["L"] in out:
            continue
        out[t["L"]] = [(h["step"], h.get("residual"), h.get("L2_u_full"),
                        h.get("fluid_mass_rel_drift"))
                       for h in t.get("history", []) if not h.get("nonfinite")]
    return out


