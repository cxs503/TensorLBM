"""Tests for the external-anchor migration study (m17788).

These pin the invariants the study in ``scripts/anchor_migration_m17788.py``
relies on, so its numbers are machine-checkable:

1. the Ghia (1982) table -> probe-layout conversion in the *new* script is
   bit-identical to the m17147 verifier's (two independent copies must agree,
   otherwise the two evidence bundles would silently disagree);
2. the Re <-> tau parameterisation is self-consistent (round-trip);
3. the no-grad Ghia-MSE sweep machinery localises a *same-chain* target at the
   true Re -- i.e. the sweep is not artefactually biased, so a biased minimum
   on the *external* (Ghia) target is a real model/discretisation effect, not a
   sweep bug.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest
import torch

from tensorlbm.diff_lid_cavity import (
    CavityGeometry,
    centreline_probes,
    initial_field,
    rollout,
    tau_from_reynolds,
)

DT = torch.float64
_ROOT = Path(__file__).resolve().parents[1]


def _load(name: str, filename: str):
    path = _ROOT / "scripts" / filename
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


AM = _load("anchor_migration_m17788", "anchor_migration_m17788.py")
V17147 = _load("verify_m17147", "verify_lid_wall_diff_m17147.py")


# ---------------------------------------------------------------------------
# 1. Ghia target consistency between the two independent copies
# ---------------------------------------------------------------------------


def test_ghia_target_matches_m17147_verifier() -> None:
    a = AM.ghia_target()
    b = V17147.ghia_target()
    assert a.shape == b.shape
    assert float((a - b).abs().max()) == 0.0


def test_ghia_target_shape_and_ordering() -> None:
    from tensorlbm.diff_lid_cavity import GHIA_STATIONS

    t = AM.ghia_target()
    assert t.shape == (2 * len(GHIA_STATIONS),)
    u_part = t[: len(GHIA_STATIONS)]
    v_part = t[len(GHIA_STATIONS):]
    assert u_part[0] < 0.0 < 0.5 < u_part[-1]
    assert v_part[0] > 0.0 > v_part[-1]


# ---------------------------------------------------------------------------
# 2. Re <-> tau parameterisation round-trip
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("n,u_lid,re", [(33, 0.08, 100.0), (129, 0.08, 100.0),
                                         (65, 0.1, 100.0)])
def test_re_tau_round_trip(n: int, u_lid: float, re: float) -> None:
    tau = AM._tau_of_re(n, re, u_lid)
    re_back = AM._re_of_tau(n, tau, u_lid)
    assert re_back == pytest.approx(re, rel=1e-12)
    # and the direct (sweep-grid) parameterisation agrees
    tau_direct = AM._tau_of_re_direct(n, re, u_lid)
    assert tau_direct == pytest.approx(tau, rel=1e-12)


def test_re_of_tau_reports_inf_at_stability_boundary() -> None:
    # tau -> 0.5 (nu -> 0) is the BGK stability boundary: Re -> inf, not a crash
    assert AM._re_of_tau(33, 0.5, 0.08) == float("inf")
    assert AM._re_of_tau(33, 0.4, 0.08) == float("inf")


# ---------------------------------------------------------------------------
# 3. sweep machinery localises a same-chain target at the true Re
# ---------------------------------------------------------------------------


def test_sweep_localises_same_chain_target_at_true_re() -> None:
    """A target generated by the chain at Re=100 must be best-matched near
    Re=100 by the *same* chain.  If the sweep machinery were biased, this would
    fail, and the external-anchor bias could not be attributed to the model."""
    torch.set_num_threads(4)
    n, steps, u_lid, re = 25, 400, 0.1, 100.0
    geom = CavityGeometry(ny=n, nx=n)
    tau_true = tau_from_reynolds(re, u_lid, length=n - 1)
    f0 = initial_field(geom)
    with torch.no_grad():
        f = rollout(f0, torch.tensor(tau_true, dtype=DT), u_lid, steps,
                    wall_mask=geom.wall_mask)
        target = centreline_probes(f, u_lid)

    re_grid = [75.0, 87.5, 100.0, 112.5, 125.0]
    curve = AM.run_sweep(geom, target, u_lid, steps, re_grid)
    finite = [c for c in curve if c["mse_vs_ghia"] is not None]
    assert len(finite) == len(re_grid)
    best = min(finite, key=lambda c: c["mse_vs_ghia"])
    # the minimum must be at (or adjacent to) the true Re, not at a grid edge
    assert best["re"] == pytest.approx(100.0, abs=12.5)
    # and the MSE at the true Re must be the smallest (or tied-smallest)
    assert best["mse_vs_ghia"] == min(c["mse_vs_ghia"] for c in finite)
