"""Invariants for the m19475 board audit of mission m19252 (TensorLBM).

These tests do not re-assert the delivery's own claims; they pin the audit's
machine-checkable findings so a later reviewer cannot silently "fix" the verdict
by editing prose. They read `artifacts/m19475_audit/verify_output.json`
(regenerated by `verify_m19252.py`) and re-query the platform DB.
"""
from __future__ import annotations

import json
import subprocess
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "artifacts" / "m19475_audit" / "verify_output.json"
WT = Path("/root/tp-agent/work/m19252")
ANCHOR = "XVAL-LBM-ROUND2-METHOD-SELECTION-CONTENT-ADDRESSE"


@pytest.fixture(scope="module")
def audit() -> dict:
    assert OUT.exists(), "run artifacts/m19475_audit/verify_m19252.py first"
    return json.loads(OUT.read_text())


def psql(sql: str) -> str:
    r = subprocess.run(
        ["runuser", "-u", "postgres", "--", "psql", "-d", "tensorplatform", "-tA", "-c", sql],
        capture_output=True, text=True, env={"PATH": "/usr/bin:/bin:/usr/sbin:/sbin"},
    )
    assert r.returncode == 0, r.stderr
    return r.stdout.strip()


def test_impl_and_artifacts_are_real(audit):
    assert audit["C1_impl_files"]["ok"] is True
    assert all(f["sha_match"] for f in audit["C1_impl_files"]["files"])
    assert audit["C2_run_artifacts"]["ok"] is True
    # A6 carries no KPI record -> the 2x2 factorial is not closed
    assert "xval/benchmark_method_selection/runs/A6_D10" in audit["C2_run_artifacts"]["incomplete"]


def test_kpi_replay_is_bit_exact(audit):
    """Numbers must be recoverable from the stored raw force histories."""
    replay = audit["C3_kpi_replay"]
    assert replay["ok"] is True
    assert replay["max_rel_diff"] == 0.0
    arms = {a["arm"]: a for a in replay["arms"]}
    assert set(arms) == {"A1", "A2", "A4"}
    a1 = arms["A1"]["kpis"]
    assert a1["cd_mean"]["replay"] == pytest.approx(1.6143262481245584, rel=0, abs=0)
    assert a1["st_fft"]["replay"] == pytest.approx(0.16899580031695963, rel=0, abs=0)


def test_no_benchmark_row_for_anchor(audit):
    """The board's only judge table has no row for this anchor -> L4 unadjudicable."""
    assert audit["C5_benchmark_rows"]["rows_for_anchor"] == 0
    assert audit["C5_benchmark_rows"]["machine_judge_possible"] is False
    assert psql("select count(*) from tensor_benchmark_cases "
                f"where anchor_slug='{ANCHOR}'") == "0"


def test_oss_row_is_nan_but_marked_pass(audit):
    """Reproduced defect: external kernel comparison renders NaN and passes hardcoded."""
    c4 = audit["C4_oss_kernel"]
    assert c4["measured_rel_l2_collision"] == pytest.approx(1.1757884876259976e-07, rel=1e-6)
    assert c4["key_mismatch_k1_vs_k1_collision"] is True
    assert c4["benchmark_reports_nan_but_marks_pass"] is True
    assert c4["benchmark_row_within_15pct"] is True


def test_closure_and_delivery_and_report_gaps(audit):
    assert audit["C7_closure"]["ok"] is False
    assert audit["C7_closure"]["runs_A1_D14_present"] is False
    assert audit["C7_closure"]["determinism"] is None
    assert audit["C7_closure"]["factorial"] == []
    assert audit["C8_delivery_git"]["ok"] is False
    assert any("run_round2_entry.py" in p
               for p in audit["C8_delivery_git"]["delivery_files_uncommitted"])
    assert psql("select count(*) from tensor_reports where mission_id=19252") == "0"


def test_verdict_level_is_3(audit):
    assert audit["level_matrix"]["L2"].startswith("PASS")
    assert audit["level_matrix"]["L3"].startswith("PASS")
    assert audit["level_matrix"]["L4"].startswith("BLOCKED")
    assert audit["level_matrix"]["verdict_level"] == 3