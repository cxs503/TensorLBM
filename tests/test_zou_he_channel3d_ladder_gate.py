"""Regression gate for the published D3Q19 Zou/He channel evidence (3-D half).

Anchor: ``XVAL-LBM-ZOU-HE-CHANNEL-INLET-OUTLET-RECONSTRUCTI``.

The 3-D arm of this anchor used to be a *single* number per width, asserted
inside ``test_zou_he_3d_inlet_outlet.py``. These tests check generated campaign
artifacts when available:

* the owner gate (``L_inf < 15 %``) and the stretch gate (``3 %``) are re-checked
  against the **raw stored profile**, not against the self-reported scalar, so a
  metric/plot disagreement cannot hide here;
* the ladder must stay monotone in ``H`` and the measured order must stay
  positive (an accidentally small single point would not survive);
* the spanwise-thickness arm (``nz = 2`` vs ``nz = 8``) must agree with the
  thin-slab arms, which is what makes the ``nz = 2`` numbers admissible at all.

Skipped (not failed) when the artifact is absent: the artifact is regenerated by
``development/verification/zou-he-channel/d3q19-ladder/campaign3d_ladder.py``.
The full campaign takes minutes and runs outside the unit-test budget.
"""
from __future__ import annotations

import json
import pathlib

import numpy as np
import pytest

OUTPUT = pathlib.Path("outputs/verification/zou-he-channel/d3q19-ladder")
if not (OUTPUT / "ladder.json").is_file():
    OUTPUT = pathlib.Path("artifacts/zou_he_channel3d")
if not (OUTPUT / "ladder.json").is_file():
    OUTPUT = (
        pathlib.Path(__file__).resolve().parents[1]
        / "development/verification/zou-he-channel/d3q19-ladder/evidence"
    )

ART = OUTPUT / "ladder.json"
BASELINE = OUTPUT / "metrics.json"

pytestmark = pytest.mark.skipif(
    not ART.exists(), reason=f"campaign artifact missing: {ART}"
)

OWNER_GATE = 0.15
STRETCH_GATE = 0.03


@pytest.fixture(scope="module")
def doc() -> dict:
    return json.loads(ART.read_text())


def _linf_from_raw(arm: dict, *, normalise: str = "continuum") -> float:
    """``L_inf`` of the flow profile, recomputed from the stored arrays.

    Two normalisations are in play and they differ by ``(H^2-1)/H^2`` (1.56 %
    at ``H = 8``), because a *discrete* parabola of width ``H`` peaks below the
    continuum one:

    * ``"continuum"`` -- ``u_max_exact = G H^2 / (8 nu)``; this is what
      :func:`tensorlbm.verification.zou_he_channel3d.simulate_channel_3d`
      reports in ``metrics["linf_rel_err"]``;
    * ``"discrete"`` -- ``max(u_exact)`` on the fluid rows (the conservative
      one).
    """
    if "u_profile" not in arm or "u_exact" not in arm:  # pragma: no cover
        return float(arm["metrics"]["linf_rel_err"])
    u = np.asarray(arm["u_profile"], dtype=float)
    ue = np.asarray(arm["u_exact"], dtype=float)
    denom = arm["metrics"]["u_max_exact"] if normalise == "continuum" else ue.max()
    return float(np.abs(u - ue).max() / denom)


def _observed_order(doc: dict) -> dict:
    """Measured order of accuracy between consecutive ladder arms (from the arms,
    not from a stored scalar, so the artifact cannot disagree with itself)."""
    ladder = [t for t in ("L08", "L16", "L32", "L48") if t in doc["arms"]]
    out = {}
    for fine, coarse in zip(ladder, ladder[1:]):
        a, b = doc["arms"][fine], doc["arms"][coarse]
        out[f"{fine}/{coarse}"] = float(
            np.log(_linf_from_raw(b) / _linf_from_raw(a)) / np.log(a["H"] / b["H"])
        )
    return out


def test_every_ladder_arm_is_inside_the_owner_gate(doc):
    ladder = [t for t in ("L08", "L16", "L32", "L48") if t in doc["arms"]]
    assert ladder, "artifact carries no ladder arm"
    for tag in ladder:
        arm = doc["arms"][tag]
        raw = _linf_from_raw(arm)
        # the reported scalar and the raw profile must agree under the same
        # normalisation ...
        if "u_profile" in arm:
            assert raw == pytest.approx(arm["metrics"]["linf_rel_err"], rel=1e-9, abs=1e-12)
        # ... and the *conservative* (discrete-peak) number clears the gates too
        assert raw < OWNER_GATE, (tag, raw)
        assert _linf_from_raw(arm, normalise="discrete") < OWNER_GATE, (tag, raw)
        assert arm["metrics"]["amp_rel_err"] < OWNER_GATE, (tag, arm["metrics"])


def test_coarse_ladder_arms_also_clear_the_three_percent_stretch_gate(doc):
    for tag in ("L08", "L16", "L32", "L48"):
        if tag in doc["arms"]:
            assert _linf_from_raw(doc["arms"][tag], normalise="discrete") < STRETCH_GATE, (tag, _linf_from_raw(doc["arms"][tag]))


def test_ladder_is_monotone_and_the_observed_order_is_positive(doc):
    ladder = [t for t in ("L08", "L16", "L32", "L48") if t in doc["arms"]]
    if len(ladder) < 2:
        pytest.skip("fewer than two ladder arms in this artifact")
    order = _observed_order(doc)
    for key, p in order.items():
        assert p > 0.0, (key, p)  # refinement must not make it worse
    ladder = [t for t in ("L08", "L16", "L32", "L48") if t in doc["arms"]]
    errs = [_linf_from_raw(doc["arms"][t]) for t in ladder]
    assert errs == sorted(errs, reverse=True), list(zip(ladder, errs))


def test_spanwise_thickness_does_not_change_the_answer(doc):
    if not {"T02", "T08"} <= set(doc["arms"]):
        pytest.skip("thickness arm not in this artifact")
    a, b = doc["arms"]["T02"], doc["arms"]["T08"]
    assert b["nz"] > a["nz"]
    for key in ("linf_rel_err", "amp_rel_err", "shape_l2_rel"):
        rel = abs(b["metrics"][key] - a["metrics"][key]) / max(a["metrics"][key], 1e-12)
        assert rel < 0.5, (key, a["metrics"][key], b["metrics"][key])


def test_long_march_is_steady_and_lands_on_the_ladder_answer(doc):
    if "M16" not in doc["arms"]:
        pytest.skip("march arm not in this artifact")
    m = doc["arms"]["M16"]
    assert m["steps"] >= 24000
    assert m["metrics"]["drift_rel"] < 1e-3  # block-window drift of the peak velocity
    if "L16" in doc["arms"]:
        a = _linf_from_raw(doc["arms"]["L16"])
        b = _linf_from_raw(m)
        assert abs(b - a) < 0.5 * max(a, 1e-12), (a, b)


def test_campaign_baseline_artifact_is_honest():
    """The 3-arm campaign artifact stores the same error it advertises."""
    if not BASELINE.exists():
        pytest.skip("baseline campaign artifact missing")
    arms = json.loads(BASELINE.read_text())["arms"]
    for tag, arm in arms.items():
        assert arm["metrics"]["linf_rel_err"] < OWNER_GATE, (tag, arm["metrics"])
