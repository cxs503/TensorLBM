def test_dem_runs_and_reports_finite_resistance(small_field):
    field, _ = small_field
    cfg = DEMConfig(dt=8e-4, t_end=0.08, t_avg_start=0.04, relax_steps=20)
    dem = FloeDEM(field, cfg)
    summary = dem.run()
    assert math.isfinite(summary["R_ice_contact_mean"])
    assert math.isfinite(summary["P_hull_mean"])
    assert summary["max_overlap_rel"] < 1.0
    assert np.all(np.isfinite(dem.vx)) and np.all(np.isfinite(dem.vy))


def test_dem_relax_reduces_overlap(small_field):
    field, _ = small_field
    cfg = DEMConfig(dt=8e-4, t_end=0.02, t_avg_start=0.01, relax_steps=60)
    dem = FloeDEM(field, cfg)
    dem.relax()
    assert dem.max_overlap_rel < 0.2


