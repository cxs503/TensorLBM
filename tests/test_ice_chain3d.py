def test_kvlcc2_block_coefficient_gate():
    hull = make_hull()
    v = hull.verify()
    assert v["pass_cb"], f"Cb = {v['cb']:.4f} vs {v['cb_target']:.4f}"
    assert v["cb_rel_error"] < 0.01
    # independent check: waterplane coefficient (not used in the fit)
    assert v["cwp_rel_error"] < 0.05
    assert v["cm_rel_error"] < 0.01


def test_hull_outline_and_entrance_angle():
    hull = make_hull()
    b = hull.outline(np.array([0.0, 50.0, 115.0, 200.0, 230.0]), ICE_LEVEL_Z)
    assert b[0] < 1e-6 and b[-1] < 1e-6          # closes at AP and FP
    assert b[2] == pytest.approx(0.5 * hull.B, rel=1e-3)   # parallel midbody
    assert 5.0 < np.degrees(np.arctan(abs((b[3] - b[4]) / 30.0))) < 90.0


def test_signed_distance_sign():
    hull = make_hull()
    def phi(x, y, z):
        return float(np.asarray(hull.signed_distance(x, y, z)).ravel()[0])

    # inside the hull (midbody, below the waterline)
    assert phi(115.0, 0.0, 7.0) < 0.0
    # well outside
    assert phi(115.0, 40.0, 7.0) > 0.0
    # above the waterline / below the keel is water
    assert phi(115.0, 0.0, 20.0) > 0.0


