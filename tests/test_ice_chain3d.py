def test_floe_field_statistics(small_field):
    field, cfg = small_field
    assert field.n > 100
    audit = audit_floe_field(field)
    assert audit["concentration_rel_error"] < 0.10
    assert audit["pass_d50"], audit["d50_rel_error"]


def test_floe_field_keeps_clear_of_hull(small_field):
    field, cfg = small_field
    hull = make_hull()
    xh = np.clip(hull.L_pp - field.x, 0.0, hull.L_pp)
    b = hull.outline(xh, ICE_LEVEL_Z)
    inside = (field.x >= 0.0) & (field.x <= hull.L_pp)
    clearance = np.abs(field.y) - b - 0.5 * field.d
    assert np.all(clearance[inside] > 0.0), "floe overlaps the hull footprint"


def test_floe_field_no_large_overlap(small_field):
    from scipy.spatial import cKDTree
    field, _ = small_field
    pairs = cKDTree(np.stack([field.x, field.y], 1)).query_pairs(
        r=float(field.d.max()), output_type="ndarray")
    if pairs.size == 0:
        return
    i, j = pairs[:, 0], pairs[:, 1]
    dist = np.hypot(field.x[j] - field.x[i], field.y[j] - field.y[i])
    pen = 0.5 * (field.d[i] + field.d[j]) - dist
    rel = pen / np.minimum(field.d[i], field.d[j])
    assert rel.max() < 0.10, f"packing overlap {rel.max():.3f}"


