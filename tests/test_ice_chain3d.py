def test_first_principles_scalings():
    r = ref.clearing_momentum(B=32.29, h=0.15, U=1.5, C_i=0.6)
    assert r == pytest.approx(917.0 * 0.6 * 0.15 * 32.29 * 2.25, rel=1e-12)
    assert ref.submersion_estimate(32.29, 14.5, 0.15, 0.6) > 0.0
    r1 = ref.clearing_momentum(B=32.29, h=0.15, U=2.0, C_i=0.6)
    assert r1 / r == pytest.approx((2.0 / 1.5) ** 2, rel=1e-12)


def test_ittc57_friction_is_monotone():
    assert ref.ittc57_cf(1e6) > ref.ittc57_cf(1e9) > 0.0
    out = ref.ittc_friction_reference()
    assert 1.0e4 < out["R_friction_N"] < 1.0e5


def test_in_repo_baseline_is_flagged_out_of_domain():
    base = ref.in_repo_riska()
    assert base["provenance"] == "IN_REPO_BASELINE"
    assert base["R_total_N"] > ref.clearing_momentum(32.29, 0.15, 1.5, 0.6) * 10


def test_gci_recovers_known_order():
    # f(h) = f0 + a h^2 sampled at r = 1.5 -> observed order 2
    f0, a = 10.0, 3.0
    hs = [1.0, 1.5, 2.25]
    f = [f0 + a * h ** 2 for h in hs]
    out = ref.gci(f[0], f[1], f[2], r=1.5)
    assert out["valid"]
    assert out["p_apparent"] == pytest.approx(2.0, rel=1e-6)
    assert out["f_extrapolated"] == pytest.approx(f0, rel=1e-6)
    # analytic GCI for this sequence: |(f2-f1)/f1| / (r^p - 1)
    # Roache three-grid safety factor Fs = 1.25 is applied since 2026-11-12
    # (docs/GCI_CONVENTION_AUDIT.md); before that the site reported Fs = 1.
    assert out["GCI_fine"] == pytest.approx(1.25 * (3.75 / 13.0) / (1.5 ** 2 - 1.0), rel=1e-6)